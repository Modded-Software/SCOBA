"""Place the resource lines in the built map, fit trees and units, check.

apply() runs after melee_map and before footprints (R-BASE-31): plan on bare
terrain, move trees and units out of the lines, write the piles, the site
table `scripts/app/data/base_sites.galaxy` and a report.
check() is the validator: line counts, pile counts, the hall gap, no
overlap, no tree or unit in a keep-out, the table equal to the placed sites.
"""
from __future__ import annotations

import re
from pathlib import Path

from flora import config as flora_config
from flora import terrain as terrain_mod

from . import config
from .fit import fit, inside
from .sites import HALL_GAP, Line, Plan, cells, ground, hall_cells, keepout, plan

PILE = re.compile(r'<ObjectUnit Id="(\d+)" Position="([^"]+)" Scale="1,1,1" UnitType="(MineralField|VespeneGeyser)"/>')


def piles(lines: list[Line]) -> list[tuple[str, float, float]]:
    out = []
    for line in lines:
        out += [("MineralField", x, y) for x, y in line.fields]
        out += [("VespeneGeyser", x, y) for x, y in line.geysers]
    return out


def objects_xml(lines: list[Line], first_id: int) -> str:
    """Placed piles, player 0, ids after every id in Objects."""
    if first_id + len(piles(lines)) > 2**31 - 1:
        raise SystemExit(f"resources: object ids overflow from {first_id}")
    return "".join(
        f'    <ObjectUnit Id="{first_id + i}" Position="{x:g},{y:g},0" Scale="1,1,1" UnitType="{kind}"/>\n'
        for i, (kind, x, y) in enumerate(piles(lines)))


def galaxy(sites: list[Line]) -> str:
    out = [
        "// Generated by scripts/mapgen/resources/build.py. Do not edit.",
        "// Expansion sites (SPEC-BASE-AI 4.7a): name and hall point. The piles are placed map units.",
        f"const int c_SITE_MAX = {config.SITE_COUNT};",
        "point[c_SITE_MAX] gv_siteAt;",
        "string[c_SITE_MAX] gv_siteName;",
        "int gv_siteCount;",
        "",
        "void gf_BaseSitesLoad () {",
    ]
    for i, line in enumerate(sites):
        out.append(f'    gv_siteAt[{i}] = Point({line.hall[0]:.1f}, {line.hall[1]:.1f}); gv_siteName[{i}] = "{line.name}";')
    out += [f"    gv_siteCount = {len(sites)};", "}", ""]
    return "\n".join(out)


def report(p: Plan, moved, problems: list[str]) -> str:
    rows = [f"lines {len(p.lines())} piles {len(piles(p.lines()))} moved {len(moved)}"]
    for line in p.lines():
        rows.append(f"line {line.name} hall {line.hall[0]},{line.hall[1]}")
    rows += [f"moved {m.kind} {m.ident} {m.old[0]:g},{m.old[1]:g} -> {m.new[0]:g},{m.new[1]:g}" for m in moved]
    rows += [f"problem {x}" for x in problems]
    return "\n".join(rows) + "\n"


def apply(map_dir: Path) -> bool:
    map_dir = Path(map_dir)
    marker = map_dir / config.MARKER
    if marker.exists():
        return False
    objects = map_dir / "Objects"
    raw = objects.read_bytes()
    newline = "\r\n" if b"\r\n" in raw else "\n"
    text = raw.decode("utf-8").replace("\r\n", "\n")
    if 'UnitType="MineralField"' in text or 'UnitType="VespeneGeyser"' in text:
        raise SystemExit("resources: Objects already has resources")
    p = plan(map_dir)
    g = ground(map_dir)
    terrain = terrain_mod.load(map_dir)
    # New spots need pathable ground only: the camps stand in water.
    text, moved, fit_problems = fit(text, keepout(p.lines(), g.good.shape[0]), terrain.pathable, terrain)
    problems = p.problems + fit_problems
    (map_dir / config.REPORT).write_text(report(p, moved, problems), encoding="utf-8")
    if problems:
        raise SystemExit("resources failed:\n" + "\n".join(problems))
    end = text.rindex("</PlacedObjects>")
    first_id = max(int(v) for v in re.findall(r'\bId="(\d+)"', text)) + 1
    text = text[:end] + objects_xml(p.lines(), first_id) + text[end:]
    objects.write_bytes(text.replace("\n", newline).encode("utf-8"))
    (map_dir / config.DATA_FILE).write_text(galaxy(p.sites), encoding="utf-8")
    marker.write_text(f"lines={len(p.lines())} moved={len(moved)}\n", encoding="utf-8")
    return True


def placed_lines(map_dir: Path) -> list[Line]:
    """Lines from the report halls and the placed piles: each pile to its nearest hall."""
    rows = (map_dir / config.REPORT).read_text(encoding="utf-8").splitlines()
    halls = []
    for row in rows:
        if row.startswith("line "):
            _l, name, _h, xy = row.split()
            x, y = xy.split(",")
            halls.append((name, (int(x), int(y))))
    text = (map_dir / "Objects").read_text(encoding="utf-8")
    groups = {name: ([], []) for name, _h in halls}
    for _i, pos, kind in PILE.findall(text):
        x, y = (float(v) for v in pos.split(",")[:2])
        name = min(halls, key=lambda h: (h[1][0] - x) ** 2 + (h[1][1] - y) ** 2)[0]
        groups[name][0 if kind == "MineralField" else 1].append((x, y))
    return [Line(name, hall, tuple(groups[name][0]), tuple(groups[name][1])) for name, hall in halls]


def check(map_dir: Path) -> list[str]:
    map_dir = Path(map_dir)
    if not (map_dir / config.REPORT).exists():
        return [f"resources: no {config.REPORT}"]
    errors = []
    lines = placed_lines(map_dir)
    mains = [ln for ln in lines if ln.name.startswith("main")]
    sites = [ln for ln in lines if not ln.name.startswith("main")]
    if len(mains) != config.MAIN_COUNT or len(sites) != config.SITE_COUNT:
        errors.append(f"resources: {len(mains)} mains, {len(sites)} sites; want {config.MAIN_COUNT}, {config.SITE_COUNT}")
    used: set = set()
    for ln in lines:
        if len(ln.fields) != config.FIELDS or len(ln.geysers) != config.GEYSERS:
            errors.append(f"resources: {ln.name} has {len(ln.fields)} fields, {len(ln.geysers)} geysers")
        near = set(hall_cells(ln.hall, HALL_GAP))
        hall = set(hall_cells(ln.hall))
        if used & hall:
            errors.append(f"resources: {ln.name} hall overlaps another line")
        used |= hall
        for size, ps in ((config.FIELD_SIZE, ln.fields), (config.GEYSER_SIZE, ln.geysers)):
            for px, py in ps:
                cs = set(cells(px, py, size))
                if cs & near:
                    errors.append(f"resources: {ln.name} pile at ({px:g},{py:g}) within {HALL_GAP} of its hall")
                if cs & used:
                    errors.append(f"resources: {ln.name} pile at ({px:g},{py:g}) overlaps")
                used |= cs
    text = (map_dir / "Objects").read_text(encoding="utf-8")
    errors += [f"resources: {x}" for x in inside(text, keepout(lines, flora_config.MAP_CELLS))]
    table = map_dir / config.DATA_FILE
    have = table.read_text(encoding="utf-8").replace("\r\n", "\n") if table.exists() else ""
    if have != galaxy(sites):
        errors.append(f"resources: {config.DATA_FILE} does not match the placed sites")
    return errors


def main() -> int:
    """Write the empty table into src/ (the build writes the real one)."""
    from project_root import project_root

    path = project_root() / "src" / "SCOBA.SC2Map" / config.DATA_FILE
    path.write_text(galaxy([]), encoding="utf-8")
    print(f"wrote empty table {path}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
