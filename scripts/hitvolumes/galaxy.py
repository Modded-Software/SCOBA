"""Galaxy data for the TPS pick (R-TPS-84), from scripts/data/hit_volumes.json.

Writes src/SCOBA.SC2Map/scripts/app/data/:

- hit_volumes_size.galaxy: the table sizes and the largest reach;
- hit_volumes_<n>.galaxy: load functions, one call per type and per shape;
- hit_volumes_load.galaxy: includes the chunks, defines gf_HvLoad.

The files are committed. `--check` (and validate-map) fails when they differ
from what the JSON gives. Model space as in the JSON: z up, scale baked in,
then every shape scaled by HV_INFLATE about the unit origin.
A capsule is stored as its end A, unit axis, and length.

usage (from scripts/): uv run python -m hitvolumes.galaxy [--check]
"""

from __future__ import annotations

import argparse
import json
import re
import sys
from pathlib import Path

from project_root import project_root

from . import fresh
from .ray import Shape

ROOT = project_root()
HARNESS = ROOT / "scripts" / "testkit" / "galaxy"
JSON = ROOT / "scripts" / "data" / "hit_volumes.json"
OUT_DIR = ROOT / "src" / "SCOBA.SC2Map" / "scripts" / "app" / "data"
SIZE = "hit_volumes_size.galaxy"
LOAD = "hit_volumes_load.galaxy"
CHUNK = "hit_volumes_{}.galaxy"
INCLUDE = "scripts/app/data/"
CHUNK_LINES = 440
CONSTANTS = ROOT / "src" / "SCOBA.SC2Map" / "scripts" / "app" / "core" / "constants.galaxy"
RANGE_RE = re.compile(r"const fixed c_SCOBA_CROSSHAIR_MAX_RANGE = ([0-9.]+);")
# Every pick volume is 15% larger than the measured model shape, scaled
# about the unit origin (SPEC-TPS 5.8). The JSON keeps the measured shapes.
HV_INFLATE = 1.15
# Never picked, so no volume is generated. Invulnerable scenery (UnitData):
# Hive, SCOBAOvermind, PsiDecimator. TerranDropPod: the escort pods fall
# through the lanes at the hero drop; the m3 box is the whole fall path
# (reach 147), not the pod (tps 20261123-134920: picked on the test lane).
# The same for the Zerg lane and scenery pods (ZergDropPod reach 71, Large
# 47) and the hero pod (SCOBAHeroPod 106): the crosshair started inside the
# ZergDropPod box 50 away and the reticle went gray (SCOBAAIMLOG marks,
# operator 2026-11-27). test_hit_volume_data fails on a new such box.
HV_UNPICKABLE = frozenset({
    "Hive", "SCOBAOvermind", "PsiDecimator", "TerranDropPod",
    "ZergDropPod", "ZergDropPodLarge", "SCOBAHeroPod",
})
# A bounds-only volume (no hit shapes in the m3) wider than this is the
# whole animation path, not the body.
HV_BOUNDS_REACH_MAX = 20.0
HEADER = "// GENERATED by scripts/hitvolumes/galaxy.py from scripts/data/hit_volumes.json. Do not edit.\n"
Vec3 = tuple[float, float, float]


def num(v: float) -> str:
    """A Galaxy fixed literal, four decimals."""
    text = f"{v + 0.0:.4f}"
    return "0.0000" if text == "-0.0000" else text


def sub(a: Vec3, b: Vec3) -> Vec3:
    return (a[0] - b[0], a[1] - b[1], a[2] - b[2])


def length(v: Vec3) -> float:
    return (v[0] * v[0] + v[1] * v[1] + v[2] * v[2]) ** 0.5


def shape_call(s: Shape) -> str:
    if s["k"] == "sphere":
        return f"    gf_HvSphere({', '.join(num(v) for v in (*s['c'], s['r']))});"
    if s["k"] == "capsule":
        a, b = tuple(s["a"]), tuple(s["b"])
        span = length(sub(b, a))
        if span == 0.0:
            return f"    gf_HvSphere({', '.join(num(v) for v in (*a, s['r']))});"
        axis = tuple(x / span for x in sub(b, a))
        return f"    gf_HvCapsule({', '.join(num(v) for v in (*a, *axis, span, s['r']))});"
    if s["k"] == "box":
        values = (*s["c"], *s["u"][0], *s["u"][1], *s["u"][2], *s["h"])
        return f"    gf_HvBox({', '.join(num(v) for v in values)});"
    raise ValueError(f"unknown shape kind {s['k']!r}")


def bound(shapes: list[Shape]) -> float:
    """Distance from the unit origin that no part of the volume passes."""
    out = 0.0
    for s in shapes:
        if s["k"] == "sphere":
            out = max(out, length(tuple(s["c"])) + s["r"])
        elif s["k"] == "capsule":
            out = max(out, length(tuple(s["a"])) + s["r"], length(tuple(s["b"])) + s["r"])
        else:
            out = max(out, length(tuple(s["c"])) + length(tuple(s["h"])))
    return out


def crosshair_range(constants: Path = CONSTANTS) -> float:
    """c_SCOBA_CROSSHAIR_MAX_RANGE from the map constants."""
    match = RANGE_RE.search(constants.read_text(encoding="utf-8"))
    if match is None:
        raise ValueError(f"c_SCOBA_CROSSHAIR_MAX_RANGE not found in {constants}")
    return float(match.group(1))


def inflate(s: Shape, f: float) -> Shape:
    """The shape scaled by `f` about the unit origin. Box axes stay."""
    out = dict(s)
    for key in ("c", "a", "b", "h"):
        if key in s:
            out[key] = [v * f for v in s[key]]
    if "r" in s:
        out["r"] = s["r"] * f
    return out


def picked(data: dict, f: float = HV_INFLATE) -> list[tuple[str, dict]]:
    """The unit types with at least one shape, sorted by name, with shapes
    and reach scaled by `f` (the pick volumes the map uses)."""
    out = []
    for name, rec in sorted(data["units"].items()):
        if rec.get("shapes") and name not in HV_UNPICKABLE:
            rec = dict(rec, reach=rec["reach"] * f, shapes=[inflate(s, f) for s in rec["shapes"]])
            out.append((name, rec))
    return out


def pick_units(data: dict | None = None) -> dict[str, dict]:
    """Unit type -> record with the map's pick volumes."""
    return dict(picked(load_json() if data is None else data))


def render(data: dict, far: float, f: float = HV_INFLATE) -> dict[str, str]:
    """File name -> text of every generated file. A type that reaches past
    `far` (the crosshair range) is a far type: the pick finds its units by
    type, not in the circle around the hero. Shapes are scaled by `f`."""
    units = picked(data, f)
    shapes = sum(len(rec["shapes"]) for _, rec in units)
    near = [rec["reach"] for _, rec in units if rec["reach"] <= far]
    reach = max(near) if near else 0.0
    blocks = []
    for name, rec in units:
        flag = "true" if rec["reach"] > far else "false"
        lines = [f'    gf_HvType("{name}", {num(bound(rec["shapes"]))}, {flag});']
        lines += [shape_call(s) for s in rec["shapes"]]
        blocks.append(lines)
    chunks: list[list[str]] = [[]]
    for lines in blocks:
        if chunks[-1] and len(chunks[-1]) + len(lines) > CHUNK_LINES:
            chunks.append([])
        chunks[-1].extend(lines)
    files = {
        SIZE: HEADER + "// Module: data/hit_volumes_size\n\n"
        f"const int c_HV_TYPES = {len(units)};\n"
        f"const int c_HV_SHAPES = {shapes};\n"
        "// At least 1: a Galaxy array has one entry or more.\n"
        f"const int c_HV_FAR_TYPES = {max(1, sum(1 for _, rec in units if rec['reach'] > far))};\n"
        "// The farthest a near type reaches from its unit, along the ground.\n"
        f"const fixed c_HV_NEAR_REACH = {num(reach)};\n",
    }
    for i, lines in enumerate(chunks, start=1):
        files[CHUNK.format(i)] = (
            HEADER + f"// Module: data/hit_volumes_{i}\n\nvoid gf_HvLoad{i} () {{\n" + "\n".join(lines) + "\n}\n"
        )
    includes = "".join(f'include "{INCLUDE}{CHUNK.format(i)[:-7]}"\n' for i in range(1, len(chunks) + 1))
    calls = "".join(f"    gf_HvLoad{i}();\n" for i in range(1, len(chunks) + 1))
    files[LOAD] = HEADER + "// Module: data/hit_volumes_load\n\n" + includes + "\nvoid gf_HvLoad () {\n" + calls + "}\n"
    return files


def load_json(path: Path = JSON) -> dict:
    return json.loads(path.read_text(encoding="utf-8"))


def stale(out_dir: Path, files: dict[str, str]) -> list[str]:
    """Problems: a file missing or different, or an extra chunk on disk."""
    problems = []
    for name, text in files.items():
        path = out_dir / name
        if not path.is_file():
            problems.append(f"hit volumes: {name} missing; run hitvolumes.galaxy")
        elif path.read_text(encoding="utf-8") != text:
            problems.append(f"hit volumes: {name} differs from scripts/data/hit_volumes.json; run hitvolumes.galaxy")
    for path in sorted(out_dir.glob("hit_volumes_*.galaxy")):
        if path.name not in files:
            problems.append(f"hit volumes: {path.name} is not generated; delete it")
    return problems


def write(out_dir: Path, files: dict[str, str]) -> None:
    out_dir.mkdir(parents=True, exist_ok=True)
    for path in out_dir.glob("hit_volumes_*.galaxy"):
        if path.name not in files:
            path.unlink()
    for name, text in files.items():
        (out_dir / name).write_text(text, encoding="utf-8")


def check_map(map_dir: Path) -> list[str]:
    """validate-map: the map's data files match the committed JSON, and the
    JSON matches the map's data (fresh.py): no unit type of the map is
    unmeasured, and no measured input changed."""
    far = crosshair_range(map_dir / "scripts" / "app" / "core" / "constants.galaxy")
    data = load_json()
    problems = stale(map_dir / "scripts" / "app" / "data", render(data, far))
    return problems + fresh.problems(map_dir, data, HARNESS)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="fail when the committed files are stale")
    args = parser.parse_args()
    files = render(load_json(), crosshair_range())
    if args.check:
        problems = stale(OUT_DIR, files)
        for p in problems:
            print(p, file=sys.stderr)
        return 1 if problems else 0
    write(OUT_DIR, files)
    for name, text in sorted(files.items()):
        print(f"{OUT_DIR / name} lines={text.count(chr(10))}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
