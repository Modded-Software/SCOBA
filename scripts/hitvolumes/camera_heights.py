"""Camera heights (R-TPS-90), from scripts/data/hit_volumes.json.

The TPS / POC camera target height and arm follow the bound unit's height.
A unit's height is the top of its measured hit shapes (in-game scale baked
in: actor Scale x model ScaleMax, not inflated). The check fails when a
measured actor scale differs from the map's ActorData, or a bound unit type
has no height. Writes src/SCOBA.SC2Map/scripts/app/data/camera_heights.galaxy:
one gf_CamHeightType call per unit type with shapes. The file is committed;
`--check` (and validate-map) fails when it differs from the JSON.

usage (from scripts/): uv run python -m hitvolumes.camera_heights [--check]
"""

from __future__ import annotations

import argparse
import sys
import xml.etree.ElementTree as ET
from pathlib import Path

from .galaxy import OUT_DIR, load_json, num
from .resolve import vec3

FILE = "camera_heights.galaxy"
HEADER = "// GENERATED by scripts/hitvolumes/camera_heights.py from scripts/data/hit_volumes.json. Do not edit.\n"
# The reference unit: its height maps to the old fixed offset and arm.
REFERENCE = "ToshSCOBA"
# Every type the player can be bound to (heroes, Alt bodies, Viking forms).
BODIES = ("ToshSCOBA", "KerriganSCOBA", "SCV", "SCOBAVikingHero", "SCOBAVikingHeroAssault")


def top(shape: dict) -> float:
    """Highest z of one shape, model space, z up."""
    if shape["k"] == "sphere":
        return shape["c"][2] + shape["r"]
    if shape["k"] == "capsule":
        return max(shape["a"][2], shape["b"][2]) + shape["r"]
    if shape["k"] == "box":
        return shape["c"][2] + sum(abs(u[2]) * h for u, h in zip(shape["u"], shape["h"]))
    raise ValueError(f"unknown shape kind {shape['k']!r}")


def heights(data: dict) -> dict[str, float]:
    """Unit type -> height, for every type with shapes and a positive top."""
    out = {}
    for name, rec in sorted(data["units"].items()):
        shapes = rec.get("shapes") or []
        if shapes:
            h = max(top(s) for s in shapes)
            if h > 0.0:
                out[name] = h
    return out


def render(data: dict) -> str:
    table = heights(data)
    if REFERENCE not in table:
        raise ValueError(f"camera heights: reference {REFERENCE} has no shapes")
    lines = [f'    gf_CamHeightType("{name}", {num(h)});' for name, h in table.items()]
    return (
        HEADER
        + "// Module: data/camera_heights\n\n"
        + f"const fixed c_CAM_HEIGHT_REFERENCE = {num(table[REFERENCE])};  // {REFERENCE}\n\n"
        + "void gf_CamHeightLoad () {\n"
        + "\n".join(lines)
        + "\n}\n"
    )


def stale(out_dir: Path, text: str) -> list[str]:
    path = out_dir / FILE
    if not path.is_file():
        return [f"camera heights: {FILE} missing; run hitvolumes.camera_heights"]
    if path.read_text(encoding="utf-8") != text:
        return [f"camera heights: {FILE} differs from scripts/data/hit_volumes.json; run hitvolumes.camera_heights"]
    return []


def map_actor_scales(map_dir: Path) -> dict[str, tuple[float, float, float]]:
    """Actor id -> its Scale in the map's own ActorData (the in-game scale)."""
    path = map_dir / "Base.SC2Data" / "GameData" / "ActorData.xml"
    out = {}
    for el in ET.parse(path).getroot():
        scale = el.find("Scale")
        if el.get("id") and scale is not None and scale.get("value"):
            out[el.get("id")] = vec3(scale.get("value"))
    return out


def scale_problems(data: dict, scales: dict[str, tuple[float, float, float]]) -> list[str]:
    """Measured types whose actor Scale differs from the map's: the JSON is
    older than the data, so the heights miss the in-game scale."""
    problems = []
    for name, rec in sorted(data["units"].items()):
        want = scales.get(rec.get("actor", ""))
        got = rec.get("actorScale")
        if want is None or got is None:
            continue
        if any(abs(a - b) > 1e-4 for a, b in zip(got, want)):
            problems.append(f"camera heights: {name} measured at actor scale {got}, map has {list(want)}; run hitvolumes.measure")
    return problems


def missing_bodies(data: dict) -> list[str]:
    table = heights(data)
    return [f"camera heights: bound unit {name} has no height; run hitvolumes.measure" for name in BODIES if name not in table]


def check_map(map_dir: Path) -> list[str]:
    """validate-map: the committed file matches the JSON, the JSON matches
    the map's actor scales, and every bound unit type has a height."""
    data = load_json()
    problems = stale(map_dir / "scripts" / "app" / "data", render(data))
    problems += scale_problems(data, map_actor_scales(map_dir))
    return problems + missing_bodies(data)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="fail when the committed file is stale")
    args = parser.parse_args()
    text = render(load_json())
    if args.check:
        problems = stale(OUT_DIR, text)
        for p in problems:
            print(p, file=sys.stderr)
        return 1 if problems else 0
    (OUT_DIR / FILE).write_text(text, encoding="utf-8")
    print(f"{OUT_DIR / FILE} lines={text.count(chr(10))}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
