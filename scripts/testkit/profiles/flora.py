ROOT = project_root()


def built_path():
    return workpaths.path("SC2_BUILT_MAP")


def targets_galaxy_path():
    return workpaths.path("SC2_TESTKIT") / "flora" / "flora_targets.galaxy"


def control_json():
    return workpaths.path("SC2_TESTKIT") / "flora" / "control.json"


def stamp_path():
    return workpaths.path("SC2_BUILD_STAMP")


def control_mode() -> bool:
    return os.environ.get("SC2_FLORA_CONTROL") == "1"


def strip_flora(map_dir: Path) -> None:
    """Control map: remove every flora and hazard doodad from Objects."""
    kinds = set(flora_config.FAMILIES) | set(flora_config.HAZARD_VARIATIONS)
    objects = map_dir / "Objects"
    text = objects.read_text(encoding="utf-8")
    pattern = re.compile(r'[ \t]*<ObjectDoodad\b[^>]*\bType="(' + "|".join(sorted(kinds)) + r')"[^>]*?(?:/>|>.*?</ObjectDoodad>)\n', re.S)
    stripped, count = pattern.subn("", text)
    if count == 0:
        raise ValueError(f"control: no flora doodad found in {objects}")
    objects.write_text(stripped, encoding="utf-8")
    print(f"flora control: stripped {count} doodads")
PLANTS_PER_FAMILY = 4
# Waypoints this far apart along each lane. flora.galaxy counts one as reached
# within c_FL_REACH = 2.5 (hero collision, crowding).
WAYPOINT_STEP = 20.0


def _plant_probes(p, terrain) -> list[tuple[str, float, float]]:
    by_kind = defaultdict(list)
    for plant in p.plants:
        x, y = int(plant.x), int(plant.y)
        if terrain.pathable[y, x] and terrain.depth[y, x] < flora_config.SHALLOW:
            by_kind[plant.kind].append(plant)
    out = []
    for kind in sorted(by_kind):
        items = by_kind[kind]
        stride = max(1, len(items) // PLANTS_PER_FAMILY)
        out += [(kind, pl.x, pl.y) for pl in items[::stride][:PLANTS_PER_FAMILY]]
    return out


def _waypoints(lane) -> list[tuple[float, float]]:
    points, walked = [lane.points[0]], 0.0
    for a, b in zip(lane.points, lane.points[1:]):
        walked += math.hypot(b[0] - a[0], b[1] - a[1])
        if walked >= WAYPOINT_STEP:
            points.append(b)
            walked = 0.0
    if points[-1] != lane.points[-1]:
        points.append(lane.points[-1])
    return points


def _split_waypoint(lane, waypoints) -> int:
    sx, sy = lane.points[lane.split]
    return min(range(len(waypoints)), key=lambda i: math.hypot(waypoints[i][0] - sx, waypoints[i][1] - sy))


GROUND_SAMPLES = 8  # per kind
GROUND_TOLERANCE_CU = 25  # 0.25 units, in centi-units


def _ground_samples() -> list[tuple[str, float, float, float]]:
    """Up to GROUND_SAMPLES placed doodads per flora/hazard kind, with the z written to Objects."""
    by_kind: dict[str, list] = {}
    for kind, x, y, z, _abs in placed_doodads(built_path()):
        by_kind.setdefault(kind, []).append((kind, x, y, z))
    out = []
    for kind in sorted(by_kind):
        items = by_kind[kind]
        step = max(1, len(items) // GROUND_SAMPLES)
        out.extend(items[::step][:GROUND_SAMPLES])
    return out


def targets_galaxy() -> tuple[str, dict]:
    p = plan(built_path())
    terrain = terrain_mod.load(built_path())
    lines = ["// Generated by scripts/testkit/profiles/flora.py from the built map.", "void gf_FloraTargets () {"]
    plants = _plant_probes(p, terrain)
    for i, (kind, x, y) in enumerate(plants):
        lines.append(f'    gf_FlProbe("plants", "p{i:03d}", {x:.3f}, {y:.3f});')
    trunks = _trunks()
    for i, (_ident, x, y) in enumerate(trunks):
        lines.append(f'    gf_FlProbe("plants", "trunk{i:03d}", {x:.3f}, {y:.3f});')
    for i, h in enumerate(p.hazards):
        lines.append(f'    gf_FlProbe("hazards", "h{i:03d}", {h.x:.3f}, {h.y:.3f});')
    ground = _ground_samples()
    for i, (_kind, x, y, _z) in enumerate(ground):
        lines.append(f'    gf_FlGround("g{i:03d}", {x:.3f}, {y:.3f});')
    lanes = {}
    for lane in p.lanes:
        waypoints = _waypoints(lane)
        split = _split_waypoint(lane, waypoints)
        lanes[lane.index] = (len(waypoints), split)
        section = f"lane{lane.index}"
        lines.append(f'    gf_FlLaneBegin("{section}", {waypoints[0][0]:.3f}, {waypoints[0][1]:.3f});')
        for k, (x, y) in enumerate(waypoints[1:], start=1):
            lines.append(f'    gf_FlLaneStep("{section}", {k}, {x:.3f}, {y:.3f});')
        lines.append(f'    gf_FlLaneEnd("{section}", {len(waypoints) - 1});')
    lines.append("}")
    heights = _height_refs()
    lines.append("void gf_FloraHeightTargets () {")
    for i, (kind, x, y, z) in enumerate(heights):
        lines.append(f'    gf_FlHeights("r{i:02d}", Point({x:.3f}, {y:.3f}));  // {kind} editor z {z}')
    lines.append("}")
    meta = {"heights": heights, "ground": ground, "plants": plants, "trunks": trunks, "hazards": p.hazards, "lanes": lanes}
    return "\n".join(lines) + "\n", meta


def _height_refs() -> list[tuple[str, float, float, float]]:
    """Editor-placed (non-flora) doodads: 4 with HeightAbsolute, 4 trees without it."""
    text = (built_path() / "Objects").read_text(encoding="utf-8")
    flora = set(flora_config.FAMILIES) | set(flora_config.HAZARD_VARIATIONS)
    absolute, trees = [], []
    pattern = r'<ObjectDoodad\b[^>]*\bPosition="([^"]+)"[^>]*\bType="([^"]+)"[^>]*?(/>|>(.*?)</ObjectDoodad>)'
    for m in re.finditer(pattern, text, re.S):
        if m.group(2) in flora:
            continue
        x, y, z = (float(v) for v in m.group(1).split(",")[:3])
        if 'HeightAbsolute" Value="1"' in (m.group(4) or ""):
            absolute.append((m.group(2) + "/abs", x, y, z))
        elif m.group(2).startswith("ZerusTree"):
            trees.append((m.group(2) + "/rel", x, y, z))
    return absolute[:: max(1, len(absolute) // 4)][:4] + trees[:: max(1, len(trees) // 4)][:4]


def _trunks() -> list[tuple[str, float, float]]:
    """Shape centres of the largest trees: deep inside their blocker."""
    trees = scene_mod.load(built_path()).trees
    out = []
    for tree in sorted(trees, key=lambda t: (-t.scale, t.ident)):
        xs = [x for x, _ in tree.polygon]
        ys = [y for _, y in tree.polygon]
        cx, cy = (min(xs) + max(xs)) / 2, (min(ys) + max(ys)) / 2
        if inside(tree.polygon, cx, cy) and edge_distance(tree.polygon, cx, cy) >= 1.0:
            out.append((tree.ident, cx, cy))
        if len(out) == 8:
            break
    return out


def map_spec() -> TestMapSpec:
    text, meta = targets_galaxy()
    print(f"flora targets: plants={len(meta['plants'])} trunks={len(meta['trunks'])} hazards={len(meta['hazards'])}"
          f" lanes={ {k: v for k, v in meta['lanes'].items()} }")
    targets_galaxy_path().parent.mkdir(parents=True, exist_ok=True)
    targets_galaxy_path().write_text(text, encoding="utf-8")
    return TestMapSpec(
        profile="flora",
        source=built_path(),
        output=profile_output("flora"),
        bank_names=PROFILE_BANKS["flora"],
        galaxy_files=(
            ROOT / "scripts" / "testkit" / "galaxy" / "common.galaxy",
            ROOT / "scripts" / "testkit" / "galaxy" / "flora.galaxy",
            targets_galaxy_path(),
        ),
        galaxy_includes=(
            "scripts/test/flora/common",
            "scripts/test/flora/flora",
            "scripts/test/flora/flora_targets",
        ),
        init_calls=("gt_Flora_Init();",),
        patch=strip_flora if control_mode() else None,
    )


def on_ready(ctx, data: dict) -> None:
    return


def check(ctx, data: dict, checks) -> None:
    for error in ctx.errors:
        print(f"{error} FAIL")
        checks.failures += 1
    checks.eq("meta", "", "done", 1)
    checks.eq("meta", "", "realClicks", 0)
    text, meta = targets_galaxy()
    readings = data.get("heights", {})
    print(f"heights hero: {readings.get('hero')} unit: {readings.get('heroUnit')}")
    for i, (kind, x, y, z) in enumerate(meta["heights"]):
        print(f"heights r{i:02d} {kind} ({x},{y}) objects z {z} | ground|air|glide|cliff|point: {readings.get(f'r{i:02d}')}")
    if not control_mode():
        ground = data.setdefault("ground", {})
        off = []
        for i, (kind, x, y, z) in enumerate(meta["ground"]):
            engine = ground.get(f"g{i:03d}")
            if engine is None or abs(int(engine) - round(z * 100)) > GROUND_TOLERANCE_CU:
                off.append((kind, x, y, z, None if engine is None else int(engine) / 100))
        print("ground control (centi-units): " + str({k: v for k, v in sorted(ground.items()) if k.startswith("lane")}))
        ground["sampled"] = len(meta["ground"])
        ground["offGround"] = len(off)
        print(f"ground: off by more than {GROUND_TOLERANCE_CU / 100} (kind, x, y, written z, engine z): {off}")
        # Recorded only: WorldHeight reads 0 at every point in this map (run 20261115-163513),
        # so ground fit is an operator check (scripts/flora/probe.py).
    # The build stamp does not cover the flora scripts; the targets do.
    stamp = stamp_path().read_text(encoding="utf-8").strip() + "-" + hashlib.sha1(text.encode("utf-8")).hexdigest()[:10]
    plants = data.setdefault("plants", {})
    raw_p = {k: bool(v) for k, v in plants.items() if re.fullmatch(r"p\d{3}", k)}
    raw_t = {k: bool(v) for k, v in plants.items() if k.startswith("trunk")}
    plants["plantCount"] = len(raw_p)
    plants["trunkCount"] = len(raw_t)
    plants["trunkOpen"] = sum(1 for v in raw_t.values() if v)
    checks.eq("plants", "", "plantCount", len(meta["plants"]))
    checks.gt("plants", "", "trunkCount", 0)
    checks.eq("plants", "", "trunkOpen", 0)
    reached = {}
    for index in meta["lanes"]:
        raw = data.get(f"lane{index}", {})
        reached[str(index)] = sum(1 for k, v in raw.items() if k.startswith("reach") and v)

    if control_mode():
        control_json().write_text(json.dumps({"stamp": stamp, "plants": raw_p, "reached": reached}, indent=1), encoding="utf-8")
        print(f"flora control saved: {control_json()} stamp {stamp}")
    else:
        control = json.loads(control_json().read_text(encoding="utf-8")) if control_json().exists() else {}
        plants["controlStampMatches"] = control.get("stamp") == stamp
        checks.true("plants", "", "controlStampMatches")
        base = control.get("plants", {})
        by_flora = [meta["plants"][int(k[1:])] for k, v in sorted(raw_p.items()) if not v and base.get(k) is True]
        by_terrain = [meta["plants"][int(k[1:])] for k, v in sorted(raw_p.items()) if not v and base.get(k) is False]
        plants["blockedByFlora"] = len(by_flora)
        plants["judged"] = sum(1 for k in raw_p if base.get(k) is True)
        print(f"plants blocked by flora: {by_flora}")
        print(f"plants on ground the control already blocks (not judged): {by_terrain}")
        checks.eq("plants", "", "blockedByFlora", 0)
        checks.gt("plants", "", "judged", len(meta["plants"]) // 2)
        for index in meta["lanes"]:
            raw = data.setdefault(f"lane{index}", {})
            raw["controlReached"] = control.get("reached", {}).get(str(index), -1)

    hazards = data.setdefault("hazards", {})
    pairs = defaultdict(dict)
    for i, h in enumerate(meta["hazards"]):
        pairs[(h.lane, h.pair)][h.side] = hazards.get(f"h{i:03d}")
    hazards["hazardCount"] = sum(1 for i in range(len(meta["hazards"])) if f"h{i:03d}" in hazards)
    hazards["pairsUneven"] = sum(1 for sides in pairs.values() if len(set(sides.values())) != 1)
    print(f"hazard pairs (lane, pair) -> passable per side: {dict(pairs)}")
    checks.eq("hazards", "", "hazardCount", len(meta["hazards"]))
    if not control_mode():
        checks.eq("hazards", "", "pairsUneven", 0)

    for index, (count, split) in sorted(meta["lanes"].items()):
        section = f"lane{index}"
        raw = data.setdefault(section, {})
        raw["reachedCount"] = reached[str(index)]
        raw["waypointCount"] = count - 1
        times = [raw.get(f"ms{k:03d}") for k in range(1, count)]
        if all(isinstance(t, int) for t in times):
            raw["zergHalfMs"] = sum(times[:split])
            raw["terranHalfMs"] = sum(times[split:])
        print(f"{section} raw: { {k: v for k, v in sorted(raw.items()) if not k.startswith('ms')} }")
        checks.true(section, "", "startPass")
        checks.eq(section, "", "realClicks", 0)
        if not control_mode():
            # Flora and hazards must not cut a lane the bare map leaves open.
            checks.eq(section, "", "reachedCount", raw["controlReached"])
            checks.eq(section, "", "reachedCount", count - 1)


def run_spec(launch_timeout_s: float, case_timeout_s: float, run_root: Path) -> TestRunSpec:
    return TestRunSpec(
        profile="flora",
        map_name="SCOBA.SC2Map",
        map_source=profile_output("flora"),
        map_cache_name="SCOBA.SC2Map",
        bank_names=PROFILE_BANKS["flora"],
        ready_section="meta",
        ready_key="ready",
        launch_timeout_s=launch_timeout_s,
        case_timeout_s=case_timeout_s,
        run_root=run_root,
        on_ready=on_ready,
        check=check,
    )
