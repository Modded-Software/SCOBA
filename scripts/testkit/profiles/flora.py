"""Flora and lane hazards, measured in game.

From the deterministic plan of the built map (flora.build.plan):

- plants: up to PLANTS_PER_FAMILY plants per family on pathable ground.
  The point under each must be passable (plants never block). Negative
  case: a probe on a tree trunk next to them must be blocked, so a
  passable reading is not just a broken probe.
- hazards: the point under each hazard is read raw. Each pair must read
  the same on both faction sides (the engine treats both sides alike).
- lanes: the hero (invulnerable) walks each lane from the Zerg end to the
  Terran end through waypoints. Every waypoint must be reached. The time
  for each half is recorded raw.

Control: SC2_FLORA_CONTROL=1 runs the same probes and walks on the same
build with every flora doodad stripped, and saves the readings with the
build stamp. A normal run needs a control of the same build. A plant probe
fails only where the control reads passable; a probe the terrain already
blocks is reported, not judged. A lane must be reached as far as in the
control.
"""

