"""HD bake probe: a unit bake and an actor bake in the running game (SPEC-HD-TEXTURES 5.2, E-1).

The map comes from `testkit/hdbake_prep.py`: the map built from `src/`
with a store that adds a bake on `unit:Marine` and one on
`actor:Marauder`, each naming `original` for every texture.

Asserts, per baked actor (in game unless marked host):
- the actor's `Model` names the made entry `<entry>_hd_<actor>`;
- the made entry is valid, its parent is the stock entry, its `Model` is
  the copy in `Assets\\Models\\scoba_hd\\<actor>\\` (E-1: a made entry);
- every field of the `CModel` scope but `Model`, arrays by element and
  structs by member, reads the same on the made entry as on the stock one
  (E-1: it holds every field of the stock one); the differences are
  printed raw;
- a unit of that id is alive and has its actor; an actor it does not
  have reads empty (the probe can say no);
- host: the copy names no packaged texture (every texture `original`),
  while the stock entry's copy does.
Negative: Goliath has a model bake only. Its actor keeps the stock entry.
The run's log checks fail on a model that is not created or a texture
slot that is lost (`testkit/logs.py`).

Not asserted: that the copy looks like the stock model, moves and
animates as it does. Operator check.
"""

from __future__ import annotations

import json
import os
import subprocess
import sys
from pathlib import Path

import workpaths
from hdtex.sc2 import m3tex
from hdtex.sc2.packaged import HD_MODEL_DIR
from project_root import project_root

from ..map_builder import TestMapSpec
from ..runner import TestRunSpec
from .bank_checks import _report
from .registry import PROFILE_BANKS, profile_output

ROOT = project_root()


def work():
    return workpaths.path("SC2_TESTKIT") / "hdbake"


def map_path():
    return work() / "map"


def facts_path():
    return work() / "facts.json"


def cases_galaxy_path():
    return work() / "hdbake_cases.galaxy"


BAKED = ("Marine", "Marauder")
NEGATIVE = "Goliath"
OTHER = {"Marine": "Goliath", "Marauder": "Marine", "Goliath": "Marauder"}
# A CModel has dozens of fields. Fewer compared means the walk read none.
MIN_COMPARED = 20


def facts() -> dict:
    return json.loads(facts_path().read_text(encoding="utf-8"))


def prepare() -> None:
    env = {**os.environ, "PYTHONPATH": str(ROOT / "scripts")}
    subprocess.run(
        [sys.executable, "-m", "testkit.hdbake_prep", str(work())],
        check=True,
        env=env,
        cwd=ROOT,
    )


def cases_galaxy(found: dict) -> str:
    body = [
        "// Generated by scripts/testkit/profiles/hdbake.py.",
        "void gf_HdBakeCases () {",
    ]
    for actor, row in found["actors"].items():
        body.append(
            f'    gf_HbActor("{actor}", "{actor}", "{row["entry"]}", "{row["made"]}");'
        )
        if actor != NEGATIVE:
            body.append(
                f'    gf_HbFields("{actor}", "{row["entry"]}", "{row["made"]}");'
            )
        body.append(f'    gf_HbUnit("{actor}", "{actor}", "{OTHER[actor]}");')
    body.append("}")
    return "\n".join(body) + "\n"


def map_spec() -> TestMapSpec:
    prepare()
    cases_galaxy_path().write_text(cases_galaxy(facts()), encoding="utf-8")
    galaxy = ROOT / "scripts" / "testkit" / "galaxy"
    return TestMapSpec(
        profile="hdbake",
        source=map_path(),
        output=profile_output("hdbake"),
        bank_names=PROFILE_BANKS["hdbake"],
        galaxy_files=(galaxy / "common.galaxy", galaxy / "hdbake.galaxy", cases_galaxy_path()),
        galaxy_includes=(
            "scripts/test/hdbake/common",
            "scripts/test/hdbake/hdbake",
            "scripts/test/hdbake/hdbake_cases",
        ),
        init_calls=("gt_HdBakeTest_Init();",),
    )


def on_ready(ctx, data: dict) -> None:
    return


def _texture_paths(map_dir: Path, model_path: str) -> list[str] | None:
    """The texture paths a model file of the map names, or None when the map has no such file."""
    path = map_dir.joinpath(*model_path.split("\\"))
    if not path.is_file():
        return None
    return [layer.path for layer in m3tex.layers(m3tex.load(path))]


def _packaged(paths: list[str]) -> list[str]:
    return [path for path in paths if "scoba_hd" in path.lower()]


def check(ctx, data: dict, checks) -> None:
    for error in ctx.errors:
        print(f"{error} FAIL")
        checks.failures += 1
    checks.eq("meta", "", "done", 1)
    checks.eq("meta", "", "realClicks", 0)
    fresh = (workpaths.path("SC2_BUILD_STAMP")).read_text(encoding="utf-8").strip()
    stamp = str(data.get("meta", {}).get("stamp", ""))
    _report(
        checks,
        "map stamp = fresh build stamp",
        stamp == fresh,
        f"map={stamp} fresh={fresh}",
    )
    found = facts()
    for actor in (*BAKED, NEGATIVE):
        row, got = found["actors"][actor], data.get(actor, {})
        print(
            f"{actor} raw: {json.dumps({k: v for k, v in got.items() if k[:1] != 'd' or not k[1:2].isdigit()}, sort_keys=True)}"
        )
        entry, made = row["entry"], row["made"]
        _report(
            checks,
            f"{actor} stock entry valid",
            got.get("entryValid") is True,
            f"entry={entry}",
        )
        _report(
            checks,
            f"{actor} actor Model",
            got.get("actorModel") == made,
            f"got={got.get('actorModel')} want={made}",
        )
        _report(
            checks,
            f"{actor} unit alive",
            got.get("unitAlive") is True and got.get("unitType") == actor,
            f"type={got.get('unitType')} alive={got.get('unitAlive')}",
        )
        _report(
            checks,
            f"{actor} unit has its actor",
            bool(got.get("actorText")),
            f"text={got.get('actorText')!r}",
        )
        _report(
            checks,
            f"{actor} negative: no actor {OTHER[actor]}",
            not got.get("otherText"),
            f"text={got.get('otherText')!r}",
        )
        entry_path = str(got.get("entryPath", ""))
        entry_textures = _texture_paths(map_path(), entry_path) or []
        _report(
            checks,
            f"{actor} stock entry shows the model bake (host)",
            entry_path.lower().startswith(HD_MODEL_DIR.lower() + "\\")
            and bool(_packaged(entry_textures)),
            f"path={entry_path} packaged textures={len(_packaged(entry_textures))}",
        )
        if actor == NEGATIVE:
            continue
        _report(
            checks,
            f"{actor} made entry valid",
            got.get("madeValid") is True,
            f"made={made}",
        )
        _report(
            checks,
            f"{actor} made entry parent = stock entry",
            got.get("madeParent") == entry,
            f"got={got.get('madeParent')} want={entry}",
        )
        made_path = str(got.get("madePath", ""))
        folder = f"{HD_MODEL_DIR}\\{actor}\\".lower()
        _report(
            checks,
            f"{actor} made entry Model = the actor's copy",
            made_path.lower().startswith(folder),
            f"got={made_path} want={folder}*",
        )
        textures = _texture_paths(map_path(), made_path)
        _report(
            checks,
            f"{actor} copy names no packaged texture (host)",
            textures is not None and bool(textures) and not _packaged(textures),
            f"textures={textures}",
        )
        compared, differ = int(got.get("compared", 0)), int(got.get("differ", -1))
        shown = [
            f"{got.get(f'd{k}Path')}: stock={got.get(f'd{k}Stock')!r} "
            f"made={got.get(f'd{k}Made')!r}"
            for k in range(1, min(differ, 20) + 1)
        ]
        _report(
            checks,
            f"{actor} made entry reads every stock field",
            compared >= MIN_COMPARED and differ == 0,
            f"scope={got.get('scope')}/{got.get('madeScope')} compared={compared} "
            f"differ={differ} {shown}",
        )


def run_spec(
    launch_timeout_s: float, case_timeout_s: float, run_root: Path
) -> TestRunSpec:
    return TestRunSpec(
        profile="hdbake",
        map_name="SCOBA.SC2Map",
        map_source=profile_output("hdbake"),
        map_cache_name="SCOBA.SC2Map",
        bank_names=PROFILE_BANKS["hdbake"],
        ready_section="meta",
        ready_key="ready",
        launch_timeout_s=launch_timeout_s,
        case_timeout_s=case_timeout_s,
        run_root=run_root,
        on_ready=on_ready,
        check=check,
    )
