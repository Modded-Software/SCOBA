"""Water probe: engine values behind the Goliath/Queen water test and the
aim-miss splash (systems/quake.galaxy), along lines across the river.

Operator 2026-11-16: ripples and splashes showed 2-4 cells from the water,
and miss splashes never showed. The test compares the engine ground height
(WorldHeight) with the water surface of the water rects; this run records
both, so the fix rests on measured values. Raw values are printed per
sample beside the build-side estimate (flora terrain).
"""

from __future__ import annotations

from pathlib import Path

from flora import terrain as terrain_mod
from flora import config as flora_config
from flora import crush as crush_mod
from project_root import project_root

from ..map_builder import TestMapSpec
from ..runner import TestRunSpec
from .registry import PROFILE_BANKS, PROFILE_OUTPUTS

ROOT = project_root()
BUILT = ROOT / "out" / "SCOBA256.SC2Map"
POINTS_GALAXY = ROOT / "out" / "testkit" / "waterprobe" / "waterprobe_points.galaxy"
MARGIN = 12.0  # cells sampled beyond a rect on each side
STEP = 1.0
RECT_PICKS = (6, 2)  # two water rects in the middle of the river


def lines() -> list[tuple[str, list[tuple[float, float]]]]:
    """Horizontal lines through the middle of the picked rects, from dry
    ground across the water to dry ground."""
    rects = terrain_mod.water_rects(BUILT)
    out = []
    for n, i in enumerate(RECT_PICKS):
        _name, (x0, y0, x1, y1) = rects[i]
        y = (y0 + y1) / 2.0 + 0.5
        xs = []
        x = max(1.0, x0 - MARGIN)
        while x <= min(255.0, x1 + MARGIN):
            xs.append((x + 0.5, y))
            x += STEP
        out.append((f"line{n}", xs))
    return out


def points_galaxy() -> str:
    body = ["// Generated by scripts/testkit/profiles/waterprobe.py.", "void gf_WaterProbePoints () {"]
    for name, pts in lines():
        body += [f'    gf_WpSample("{name}", {k}, {x:.3f}, {y:.3f});' for k, (x, y) in enumerate(pts)]
    body.append("}")
    return "\n".join(body) + "\n"


def map_spec() -> TestMapSpec:
    POINTS_GALAXY.parent.mkdir(parents=True, exist_ok=True)
    POINTS_GALAXY.write_text(points_galaxy(), encoding="utf-8")
    galaxy = ROOT / "scripts" / "testkit" / "galaxy"
    return TestMapSpec(
        profile="waterprobe",
        source=BUILT,
        output=PROFILE_OUTPUTS["waterprobe"],
        bank_names=PROFILE_BANKS["waterprobe"],
        galaxy_files=(galaxy / "common.galaxy", galaxy / "waterprobe.galaxy", POINTS_GALAXY),
        galaxy_includes=("scripts/test/waterprobe/common", "scripts/test/waterprobe/waterprobe", "scripts/test/waterprobe/waterprobe_points"),
        init_calls=("gt_WaterProbe_Init();",),
    )


def on_ready(ctx, data: dict) -> None:
    return


def check(ctx, data: dict, checks) -> None:
    for error in ctx.errors:
        print(f"{error} FAIL")
        checks.failures += 1
    checks.eq("meta", "", "done", 1)
    checks.eq("meta", "", "realClicks", 0)
    checks.gt("meta", "", "count", 0)
    print(f"meta raw: {data.get('meta', {})}")
    t = terrain_mod.load(BUILT)
    span_depth = {}
    for sy, x0, x1, _z, d in crush_mod.water_spans(t):
        for sx in range(x0, x1):
            span_depth[(sy, sx)] = d
    for name, pts in lines():
        row = data.get(name, {})
        print(f"{name}: k x y wet splash splashCount floraGround+lift depth expected")
        wet_n = dry_n = 0
        for k, (x, y) in enumerate(pts):
            s = f"s{k}"
            cy, cx = int(y), int(x)
            depth = float(t.depth[cy, cx]) - flora_config.GROUND_LIFT
            expected = depth >= flora_config.WATER_FX_DEPTH
            visible = terrain_mod.ground_z(t, x, y) + flora_config.GROUND_LIFT
            got, splash = row.get(s + "Wet"), row.get(s + "Splash")
            print(f"  {k} {x:.1f} {y:.1f} {got} {splash} {row.get(s + 'SplashCount')} {visible:.3f} {depth:.3f} {expected}")
            # The in-game test equals the build mask, and a miss splashes
            # exactly where it is wet (negative case: dry cells never splash).
            if got != expected or splash != expected:
                print(f"  {name} s{k}: wet={got} splash={splash} want {expected} FAIL")
                checks.failures += 1
            # The splash is raised by the span's visible depth (table value);
            # negative case: a dry sample has no depth and no splash height.
            want_h = span_depth.get((cy, cx), -1.0)
            got_d, got_h = float(row.get(s + "Depth", -9)), float(row.get(s + "SplashH", -9))
            print(f"    depth={got_d:.3f} splashH={got_h:.3f} want {want_h:.3f}")
            if abs(got_d - want_h) > 0.01 or abs(got_h - want_h) > 0.01 or (expected and want_h < flora_config.WATER_FX_DEPTH):
                print(f"  {name} s{k}: depth={got_d} splashH={got_h} want {want_h} FAIL")
                checks.failures += 1
            wet_n += expected
            dry_n += not expected
        if not row or wet_n == 0 or dry_n == 0:
            print(f"{name}: needs wet and dry samples (wet {wet_n}, dry {dry_n}) FAIL")
            checks.failures += 1


def run_spec(launch_timeout_s: float, case_timeout_s: float, run_root: Path) -> TestRunSpec:
    return TestRunSpec(
        profile="waterprobe",
        map_name="SCOBA.SC2Map",
        map_source=PROFILE_OUTPUTS["waterprobe"],
        map_cache_name="SCOBA.SC2Map",
        bank_names=PROFILE_BANKS["waterprobe"],
        ready_section="meta",
        ready_key="ready",
        launch_timeout_s=launch_timeout_s,
        case_timeout_s=case_timeout_s,
        run_root=run_root,
        on_ready=on_ready,
        check=check,
    )
