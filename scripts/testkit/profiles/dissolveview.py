"""Operator view: one crushable doodad in front of Tosh at the map spawn gets
the physics message (MakeMsgSetPhysicsState simulated) through
ActorFromDoodad. The operator watches what happens; not a pass/fail test.
The actor state per second goes to the SCOBADISSOLVE bank (raw values).

Run: scripts/playtest.sh dissolveview  (launches the map for manual viewing)
"""

from __future__ import annotations

import math
from pathlib import Path

from project_root import project_root

from ..map_builder import TestMapSpec, build_instrumented_map

ROOT = project_root()
BUILT = ROOT / "out" / "SCOBA256.SC2Map"
OUTPUT = ROOT / "out" / "SCOBA256_dissolveview.SC2Map"
DOODAD_ID = 1999000001
DOODAD_TYPE = "ZerusPlantClusterLarge"
TOSH_ID = "622754155"
AHEAD = 4.0  # cells in front of Tosh


def tosh_spawn(objects: str) -> tuple[float, float, float]:
    import re

    m = re.search(rf'<ObjectUnit Id="{TOSH_ID}" Position="([^,]+),([^,]+),[^"]*" Rotation="([^"]+)"', objects)
    if not m:
        raise ValueError("dissolveview: Tosh spawn not found in Objects")
    return float(m.group(1)), float(m.group(2)), float(m.group(3))


def doodad_line(objects: str) -> str:
    # Absolute z on the visible ground, as the flora build places plants
    # (terrain ground + GROUND_LIFT, HeightOffset + HeightAbsolute flags).
    from flora import config as flora_config
    from flora import terrain as terrain_mod

    dx, dy = spot(objects)
    z = terrain_mod.ground_z(terrain_mod.load(BUILT), dx, dy) + flora_config.GROUND_LIFT
    return (
        f'    <ObjectDoodad Id="{DOODAD_ID}" Variation="0" Position="{dx:.3f},{dy:.3f},{z:.4f}" Rotation="0" Scale="1.5,1.5,1.5" Type="{DOODAD_TYPE}">\n'
        '        <Flag Index="HeightOffset" Value="1"/>\n'
        '        <Flag Index="HeightAbsolute" Value="1"/>\n'
        "    </ObjectDoodad>\n"
    )


def spot(objects: str) -> tuple[float, float]:
    x, y, rot = tosh_spawn(objects)
    return x + AHEAD * math.cos(rot), y + AHEAD * math.sin(rot)


def patch(map_dir: Path) -> None:
    objects = map_dir / "Objects"
    text = objects.read_text(encoding="utf-8")

    if f'Id="{DOODAD_ID}"' in text:
        raise ValueError("dissolveview: doodad id already used")
    if "</PlacedObjects>" not in text:
        raise ValueError("dissolveview: no </PlacedObjects> in Objects")
    objects.write_text(text.replace("</PlacedObjects>", doodad_line(text) + "</PlacedObjects>"), encoding="utf-8")


SPOT_GALAXY = ROOT / "out" / "testkit" / "dissolveview" / "dissolveview_spot.galaxy"


def map_spec() -> TestMapSpec:
    galaxy = ROOT / "scripts" / "testkit" / "galaxy"
    dx, dy = spot((BUILT / "Objects").read_text(encoding="utf-8"))
    SPOT_GALAXY.parent.mkdir(parents=True, exist_ok=True)
    SPOT_GALAXY.write_text(f"// Generated by dissolveview.py.\nconst fixed c_DV_X = {dx:.3f};\nconst fixed c_DV_Y = {dy:.3f};\n", encoding="utf-8")
    return TestMapSpec(
        profile="dissolveview",
        source=BUILT,
        output=OUTPUT,
        bank_names=("SCOBADISSOLVE",),
        galaxy_files=(SPOT_GALAXY, galaxy / "dissolveview.galaxy"),
        galaxy_includes=("scripts/test/dissolveview/dissolveview_spot", "scripts/test/dissolveview/dissolveview"),
        init_calls=("gt_DissolveView_Init();",),
        patch=patch,
    )


def main() -> None:
    print(build_instrumented_map(map_spec()))


if __name__ == "__main__":
    main()
