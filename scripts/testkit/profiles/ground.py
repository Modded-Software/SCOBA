"""Ground probe: the engine ground (t3SyncHeightMap, terrain/sync_height.py)
against the render ground, and a flyer over a hill.

Real ground is on by default. Asserts:
- grid: WorldHeight ground equals the render ground at every sample;
  negative: the engine ground is not flat (its range follows the render's);
- spots: a Marine stands on the render ground on hills and in valleys;
- viking: the hero Viking's height above the ground is the same over a
  valley and a hill, so its absolute height follows the terrain; the camera
  part is the flight height.
Raw values and a linear fit (engine = k * render + c) are printed, so a
wrong encoding shows its scale and offset.
"""

from __future__ import annotations

from pathlib import Path

import numpy as np
import workpaths
from flora import terrain as terrain_mod
from project_root import project_root
from terrain import sync_height

from ..map_builder import TestMapSpec
from ..runner import TestRunSpec
from .bank_checks import _report
from .registry import PROFILE_BANKS, profile_output

ROOT = project_root()


def built_path():
    return workpaths.path("SC2_BUILT_MAP")


def points_galaxy_path():
    return workpaths.path("SC2_TESTKIT") / "ground" / "ground_points.galaxy"


STEP = 16
EDGE = 16
SPOTS = 3  # highest and lowest pathable spots each
SPOT_GAP = 12.0
GRID_TOL = 0.15  # bilinear vs the engine's triangles on a slope
GRID_MAX = 0.5
SPOT_TOL = 0.25
VIKING_TOL = 0.3


def grid_points() -> list[tuple[float, float]]:
    return [(float(x), float(y)) for y in range(EDGE, 257 - EDGE, STEP) for x in range(EDGE, 257 - EDGE, STEP)]


def spots() -> tuple[list[tuple[float, float]], list[tuple[float, float]]]:
    """Highest and lowest pathable dry cell centres, apart from each other."""
    t = terrain_mod.load(built_path())
    n = t.height.shape[0]
    cells = [
        (float(t.height[y, x]), x + 0.5, y + 0.5)
        for y in range(EDGE, n - EDGE)
        for x in range(EDGE, n - EDGE)
        if t.pathable[y, x] and not t.wet[y, x]
    ]
    cells.sort()

    def pick(seq):
        out: list[tuple[float, float]] = []
        for _z, x, y in seq:
            if all((x - a) ** 2 + (y - b) ** 2 >= SPOT_GAP**2 for a, b in out):
                out.append((x, y))
            if len(out) == SPOTS:
                break
        return out

    return pick(reversed(cells)), pick(cells)


def points_galaxy() -> str:
    high, low = spots()
    body = ["// Generated by scripts/testkit/profiles/ground.py.", "void gf_GroundPoints () {"]
    body += [f"    gf_GtSample({k}, {x:.3f}, {y:.3f});" for k, (x, y) in enumerate(grid_points())]
    body += ["}", "", "void gf_GroundSpots () {"]
    for name, pts in (("high", high), ("low", low)):
        body += [f'    gf_GtMarine("{name}{k}", {x:.3f}, {y:.3f});' for k, (x, y) in enumerate(pts)]
    body += ["    gf_HeroSwitchTo(gv_heroViking);", "    Wait(1.5, c_timeGame);"]
    (lx, ly), (hx, hy) = low[0], high[0]
    body += [
        f'    gf_GtViking("vlow", {lx:.3f}, {ly:.3f});',
        f'    gf_GtViking("vhigh", {hx:.3f}, {hy:.3f});',
        f'    gf_GtViking("vlow2", {lx:.3f}, {ly:.3f});',
        "}",
    ]
    return "\n".join(body) + "\n"


def map_spec() -> TestMapSpec:
    points_galaxy_path().parent.mkdir(parents=True, exist_ok=True)
    points_galaxy_path().write_text(points_galaxy(), encoding="utf-8")
    galaxy = ROOT / "scripts" / "testkit" / "galaxy"
    return TestMapSpec(
        profile="ground",
        source=built_path(),
        output=profile_output("ground"),
        bank_names=PROFILE_BANKS["ground"],
        galaxy_files=(galaxy / "common.galaxy", galaxy / "ground.galaxy", points_galaxy_path()),
        galaxy_includes=("scripts/test/ground/common", "scripts/test/ground/ground", "scripts/test/ground/ground_points"),
        init_calls=("gt_GroundTest_Init();",),
    )


def on_ready(ctx, data: dict) -> None:
    return


def _f(data: dict, section: str, key: str) -> float | None:
    v = data.get(section, {}).get(key)
    return None if v is None else float(v)


def check(ctx, data: dict, checks) -> None:
    for error in ctx.errors:
        print(f"{error} FAIL")
        checks.failures += 1
    checks.eq("meta", "", "done", 1)
    checks.eq("meta", "", "realClicks", 0)
    vz = sync_height.vertex_z(built_path())
    sync = (built_path() / "t3SyncHeightMap").exists()
    _report(checks, "built map has t3SyncHeightMap", sync, f"exists={sync}")

    host, eng, air = [], [], []
    for k, (x, y) in enumerate(grid_points()):
        g = _f(data, "grid", f"s{k}Ground")
        if g is None:
            continue
        host.append(sync_height.ground_at(vz, x, y))
        eng.append(g)
        air.append(_f(data, "grid", f"s{k}Air") or 0.0)
    host_a, eng_a = np.array(host), np.array(eng)
    _report(checks, "grid samples read", len(eng) == len(grid_points()), f"got={len(eng)} want={len(grid_points())}")
    if len(eng) >= 2:
        k, c = np.linalg.lstsq(np.vstack([host_a, np.ones(len(host_a))]).T, eng_a, rcond=None)[0]
        diff = np.abs(eng_a - host_a)
        print(f"grid raw: render {host_a.min():.2f}..{host_a.max():.2f} engine {eng_a.min():.2f}..{eng_a.max():.2f} air {min(air):.2f}..{max(air):.2f} fit engine = {k:.4f} * render + {c:.3f}")
        p95 = float(np.percentile(diff, 95))
        _report(checks, "grid engine ground = render ground", p95 <= GRID_TOL and diff.max() <= GRID_MAX, f"p95={p95:.3f} max={diff.max():.3f}")
        # Negative: the engine ground is not flat.
        span_h, span_e = float(np.ptp(host_a)), float(np.ptp(eng_a))
        _report(checks, "grid engine ground not flat", span_e >= 0.9 * span_h and span_h > 1.0, f"render span={span_h:.2f} engine span={span_e:.2f}")

    for name in [f"high{i}" for i in range(SPOTS)] + [f"low{i}" for i in range(SPOTS)]:
        x, y, h = _f(data, name, "x"), _f(data, name, "y"), _f(data, name, "marineH")
        if x is None or h is None:
            _report(checks, f"{name} marine read", False, "missing")
            continue
        want = sync_height.ground_at(vz, x, y)
        g = _f(data, name, "ground")
        print(f"{name} raw: x={x:.2f} y={y:.2f} marineH={h:.3f} posZ={_f(data, name, 'marinePosZ')} ground={g} render={want:.3f}")
        # UnitGetHeight is above the engine ground: a standing Marine reads 0.
        _report(checks, f"{name} marine stands on the engine ground", abs(h) <= 0.01, f"marineH={h:.3f}")
        _report(checks, f"{name} engine ground under the marine = render", g is not None and abs(g - want) <= SPOT_TOL, f"ground={g} render={want:.3f}")

    rows = {}
    for s in ("vlow", "vhigh", "vlow2"):
        rows[s] = {k: _f(data, s, k) for k in ("vH", "vGround", "vAir", "vFlight", "vCamApplied", "vCamTargetZ")}
        print(f"{s} raw: type={data.get(s, {}).get('vType')} {rows[s]}")
    lo, hi = rows["vlow"], rows["vhigh"]
    if None in (lo["vH"], hi["vH"], lo["vGround"], hi["vGround"]):
        _report(checks, "viking read", False, "missing")
        return
    # UnitGetHeight is above the engine ground: equal over valley and hill
    # means the absolute height follows the terrain.
    _report(checks, "viking same height above ground on valley and hill", abs(lo["vH"] - hi["vH"]) <= VIKING_TOL, f"low={lo['vH']:.3f} high={hi['vH']:.3f}")
    rise_ground = hi["vGround"] - lo["vGround"]
    # Negative: the engine ground under the flyer is not flat between the spots.
    _report(checks, "engine ground rises under the viking", rise_ground > 5.0, f"ground rise={rise_ground:.3f}")
    for s in ("vlow", "vhigh"):
        fl, cam = rows[s]["vFlight"], rows[s]["vCamApplied"]
        ok = fl is not None and cam is not None and abs(fl - rows[s]["vH"]) <= 0.01
        _report(checks, f"{s} flight part = height above ground", ok, f"flight={fl} vH={rows[s]['vH']} cam={cam}")
    back = rows["vlow2"]["vH"]
    _report(checks, "viking back in the valley", back is not None and abs(back - lo["vH"]) <= VIKING_TOL, f"vlow={lo['vH']:.3f} vlow2={back}")


def run_spec(launch_timeout_s: float, case_timeout_s: float, run_root: Path) -> TestRunSpec:
    return TestRunSpec(
        profile="ground",
        map_name="SCOBA.SC2Map",
        map_source=profile_output("ground"),
        map_cache_name="SCOBA.SC2Map",
        bank_names=PROFILE_BANKS["ground"],
        ready_section="meta",
        ready_key="ready",
        launch_timeout_s=launch_timeout_s,
        case_timeout_s=case_timeout_s,
        run_root=run_root,
        on_ready=on_ready,
        check=check,
    )
