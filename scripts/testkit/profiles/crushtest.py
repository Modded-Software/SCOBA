"""Crush test: Goliaths and Queens remove the grass they walk into; Marines do not.

Targets are tall grass plants on open land, read from the built map's
crush table (scripts/app/data/flora_crush.galaxy), so indices match the game.
Whether the doodad really vanished and how the debris looks are operator
checks: a script cannot read a placed doodad.
"""

from __future__ import annotations

import math
import re
from pathlib import Path

from flora import terrain as terrain_mod
from flora.crush import DATA_FILE
from project_root import project_root

from ..map_builder import TestMapSpec
from ..runner import TestRunSpec
from .registry import PROFILE_BANKS, PROFILE_OUTPUTS

ROOT = project_root()
BUILT = ROOT / "out" / "SCOBA256.SC2Map"
TARGETS_GALAXY = ROOT / "out" / "testkit" / "crushtest" / "crushtest_targets.galaxy"
WALKERS = (("marine", "Marine"), ("goliath", "Goliath"), ("queen", "Queen"))
PER_WALKER = 3
CHAIN_MAX = 12.0  # next target within this of the previous one
GROUP_GAP = 30.0  # walker groups this far apart
SPAWN_BACK = 4.0
EDGE = 16  # keep clear of the unplayable border


def crush_table() -> list[tuple[int, float, float]]:
    text = (BUILT / DATA_FILE).read_text(encoding="utf-8")
    return [(int(i), float(x), float(y)) for i, x, y in re.findall(r"gv_crushX\[(\d+)\] = ([\d.]+); gv_crushY\[\d+\] = ([\d.]+); gv_crushZ", text)]


def groups() -> list[tuple[tuple[float, float], list[tuple[int, float, float]]]]:
    t = terrain_mod.load(BUILT)

    def open_land(x: float, y: float) -> bool:
        cx, cy = math.floor(x), math.floor(y)
        return EDGE <= cx < 256 - EDGE and EDGE <= cy < 256 - EDGE and bool(t.pathable[cy, cx]) and not bool(t.wet[cy, cx])

    land = [r for r in crush_table() if open_land(r[1], r[2]) and open_land(r[1] - SPAWN_BACK, r[2])]
    out: list = []
    used: set[int] = set()
    for start in land:
        if len(out) == len(WALKERS):
            break
        if any(math.hypot(start[1] - g[1][0][1], start[2] - g[1][0][2]) < GROUP_GAP for g in out):
            continue
        chain = [start]
        while len(chain) < PER_WALKER:
            last = chain[-1]
            near = [r for r in land if r[0] not in used and r not in chain and math.hypot(r[1] - last[1], r[2] - last[2]) <= CHAIN_MAX]
            if not near:
                break
            chain.append(min(near, key=lambda r: math.hypot(r[1] - last[1], r[2] - last[2])))
        if len(chain) == PER_WALKER:
            used.update(r[0] for r in chain)
            out.append(((start[1] - SPAWN_BACK, start[2]), chain))
    if len(out) < len(WALKERS):
        raise ValueError(f"crush test: only {len(out)} target groups on open land")
    return out


def targets_galaxy() -> tuple[str, list]:
    picked = groups()
    lines = ["// Generated by scripts/testkit/profiles/crushtest.py.", "void gf_CrushTestTargets () {", "    unit lv_u;"]
    for (section, kind), (spawn, chain) in zip(WALKERS, picked):
        lines.append(f'    lv_u = gf_CtSpawn("{kind}", {spawn[0]:.3f}, {spawn[1]:.3f});')
        for k, (i, _x, _y) in enumerate(chain):
            lines.append(f'    gf_CtWalk("{section}", "t{k}", lv_u, {i});')
        lines.append(f'    gf_CtEnd("{section}", lv_u);')
    lines.append("}")
    return "\n".join(lines) + "\n", picked


def map_spec() -> TestMapSpec:
    text, picked = targets_galaxy()
    print(f"crush targets: {[[r[0] for r in chain] for _s, chain in picked]}")
    TARGETS_GALAXY.parent.mkdir(parents=True, exist_ok=True)
    TARGETS_GALAXY.write_text(text, encoding="utf-8")
    galaxy = ROOT / "scripts" / "testkit" / "galaxy"
    return TestMapSpec(
        profile="crushtest",
        source=BUILT,
        output=PROFILE_OUTPUTS["crushtest"],
        bank_names=PROFILE_BANKS["crushtest"],
        galaxy_files=(galaxy / "common.galaxy", galaxy / "crushtest.galaxy", TARGETS_GALAXY),
        galaxy_includes=("scripts/test/crushtest/common", "scripts/test/crushtest/crushtest", "scripts/test/crushtest/crushtest_targets"),
        init_calls=("gt_CrushTest_Init();",),
    )


def on_ready(ctx, data: dict) -> None:
    return


def check(ctx, data: dict, checks) -> None:
    for error in ctx.errors:
        print(f"{error} FAIL")
        checks.failures += 1
    checks.eq("meta", "", "done", 1)
    checks.eq("meta", "", "realClicks", 0)
    checks.gt("meta", "", "count", 0)
    for section, _kind in WALKERS:
        print(f"{section} raw: {data.get(section, {})}")
        for k in range(PER_WALKER):
            checks.true(section, "", f"t{k}Arrived")
            if section == "marine":
                checks.false(section, "", f"t{k}Gone")  # negative case
            else:
                checks.true(section, "", f"t{k}Gone")
    # Negative case: the Marine walk removes nothing at all.
    checks.eq("marine", "", "removed", 0)
    checks.gt("goliath", "", "removed", PER_WALKER - 1)
    checks.gt("queen", "", "removed", 2 * PER_WALKER - 1)


def run_spec(launch_timeout_s: float, case_timeout_s: float, run_root: Path) -> TestRunSpec:
    return TestRunSpec(
        profile="crushtest",
        map_name="SCOBA.SC2Map",
        map_source=PROFILE_OUTPUTS["crushtest"],
        map_cache_name="SCOBA.SC2Map",
        bank_names=PROFILE_BANKS["crushtest"],
        ready_section="meta",
        ready_key="ready",
        launch_timeout_s=launch_timeout_s,
        case_timeout_s=case_timeout_s,
        run_root=run_root,
        on_ready=on_ready,
        check=check,
    )
