"""Water features in the game (REQ-WATER-FEATURES, SPEC-WATER-FEATURES).

Asserts, per site:
- carve: the engine ground (WorldHeight) equals the built ground on the pool
  floor and on the moved dry ground; the pool floor is under the water
  level and the moved dry ground at the pool is over it; negative: the
  ground from before the step is absent (every moved sample reads nearer
  the new ground than the old one), and ground beside the site that the
  step left alone reads as before;
- path: every pool cell the build painted is not passable; the control is the walk's start, which is passable;
- stand: a Marine put on carved ground stands on the engine ground there;
- walk: a Marine ordered to the middle of the pool walks, and never stands
  in water NO_PATH_DEPTH deep (negative case).
And the pipe unit: one unit, at its placed spot, on the ground, facing 270
(the facing at which a model is drawn as authored, hit_volumes.galaxy
c_HV_MODEL_YAW). The build takes the pipe mouths from these.
Raw values are printed, so a failure shows what the engine did.

And per rim fall group (REQ-RIM-FALLS): the basin is cut in the engine
ground (negative: the uncut ground is absent), and the basin and its rocks
block no ground the map left walkable (negative: nothing blocks; the pool
cells above are the control that a blocked cell reads as not passable).
Points on ground the map itself paints or a tree covers are listed, not
judged.

- orbit: the camera circles each site for 15 s of real time (target, yaw,
  pitch and distance read from the engine); negative: it does not follow
  the hero. The host takes 5 screenshots 3 s apart per site into the run's
  `frames/`.

Not covered: anything drawn, the dirt texture on the pool walls included
(the host tests check its mask). The screenshots decide no check. The agent
looks at them for scenery only (AGENTS.md "Screenshots"); the look stays
an operator check.
"""

