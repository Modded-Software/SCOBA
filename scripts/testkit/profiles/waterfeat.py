def game_window() -> str:
    """X id of the game window. Slow (3.2 s, 14760 windows on 2026-11-20): asked once."""
    env = {**os.environ, "DISPLAY": os.environ.get("DISPLAY", ":0")}
    tree = subprocess.run(["xwininfo", "-root", "-tree"], capture_output=True, text=True, env=env, check=True).stdout
    for line in tree.splitlines():
        if "StarCraft II" in line:
            return line.split()[0]
    raise RuntimeError("no StarCraft II window")


def shoot(ctx, name: str, window: str) -> list[tuple[float, str]]:
    """SHOTS screenshots, SHOT_GAP_S apart. Returns (seconds from the first grab to the end of this grab, file name).

    input_inject.shot looks the window up before every grab, which put the
    grabs seconds late (run 20261120-122128: a shot stamped 9 s showed the
    view after the orbit). Here the window is known, each grab is timed to
    its end, and the PNGs are made after the last grab."""
    env = {**os.environ, "DISPLAY": os.environ.get("DISPLAY", ":0")}
    start = time.monotonic()
    rows = []
    for k in range(SHOTS):
        time.sleep(max(0.0, start + k * SHOT_GAP_S - time.monotonic()))
        path = ctx.frames.dir / f"{name}-{k + 1:04d}.png"
        subprocess.run(["xwd", "-id", window, "-out", str(path) + ".xwd"], env=env, check=True)
        rows.append((time.monotonic() - start, path.name))
    for _stamp, file_name in rows:
        grab = ctx.frames.dir / (file_name + ".xwd")
        subprocess.run([os.environ.get("FFMPEG", "ffmpeg"), "-y", "-loglevel", "error", "-i", str(grab), str(ctx.frames.dir / file_name)], check=True)
        grab.unlink()
    (ctx.frames.dir / f"{name}-timestamps.tsv").write_text("".join(f"{t:.3f}\t{n}\n" for t, n in rows), encoding="utf-8")
    return rows


def on_ready(ctx, data: dict) -> None:
    """Screenshots of every orbit the harness announces, until the run is done."""
    from ..bank import find_latest_bank, read_bank

    ctx.orbit_shots = {}
    window = game_window()
    seen = 0
    deadline = time.monotonic() + HOST_DEADLINE_S
    while time.monotonic() < deadline:
        path = find_latest_bank(_docs(), PROFILE_BANKS["waterfeat"][0], 0.0)
        bank = None
        if path is not None:
            try:
                bank = read_bank(path)
            except RuntimeError:
                bank = None  # mid-write; the next poll reads it
        if bank:
            host = bank.get("wf_host", {})
            req = host.get("req") or 0
            if req > seen:
                seen = req
                name = str(host.get("name"))
                ctx.orbit_shots[name] = shoot(ctx, name, window)
                print(f"host shots req={req} {name}: {[n for _t, n in ctx.orbit_shots[name]]}", flush=True)
                continue
            if bank.get("meta", {}).get("done") == 1:
                return
        time.sleep(0.05)
    ctx.errors.append("host shot loop: run not done before the deadline")


def _f(data: dict, section: str, key: str) -> float | None:
    v = data.get(section, {}).get(key)
    return None if v is None else float(v)


def _heights(checks, data: dict, sc: Scene, section: str, points: list[Point], level: float, side: str) -> None:
    """Engine ground of one sample class against the built ground."""
    got = [_f(data, section, f"s{k}Ground") for k in range(len(points))]
    if not points or None in got:
        _report(checks, f"{section} samples read", False, f"got={sum(v is not None for v in got)} want={len(points)} (at least 1)")
        return
    eng = np.array(got)
    new = np.array([bilinear(sc.vz, x, y) for x, y in points])
    old = np.array([bilinear(sc.before, x, y) for x, y in points])
    print(f"{section} raw: n={len(points)} engine {eng.min():.3f}..{eng.max():.3f} built {new.min():.3f}..{new.max():.3f} before {old.min():.3f}..{old.max():.3f} level {level:.3f}")
    off = np.abs(eng - new)
    _report(checks, f"{section} engine ground = built ground", float(off.max()) <= VERTEX_TOL, f"max={off.max():.3f} tol={VERTEX_TOL}")
    if side == "pool":
        _report(checks, f"{section} pool floor under the water level", float(eng.max()) < level, f"highest={eng.max():.3f} level={level:.3f}")
    if side == "dry":
        _report(checks, f"{section} moved shore over the water level", float(eng.min()) > level, f"lowest={eng.min():.3f} level={level:.3f}")
    if side == "far":
        # Negative: the step did not move this ground, and the engine agrees.
        still = np.abs(eng - old)
        _report(checks, f"{section} ground beside the site did not move", float(still.max()) <= VERTEX_TOL, f"max={still.max():.3f}")
        return
    # Negative: the ground from before the step is absent.
    moved = np.abs(new - old) >= MOVED
    stale = int((np.abs(eng - old)[moved] <= np.abs(eng - new)[moved]).sum())
    _report(checks, f"{section} ground from before the step is absent", int(moved.sum()) >= 3 and stale == 0, f"moved={int(moved.sum())} (at least 3) still old={stale}")


def _cells(checks, data: dict, section: str, points: list[Point], what: str) -> None:
    got = [data.get(section, {}).get(f"s{k}Pass") for k in range(len(points))]
    is_open = [f"{x:.1f},{y:.1f}" for (x, y), v in zip(points, got) if v is not False]
    _report(checks, f"{section} {what} are not passable", bool(points) and not is_open, f"cells={len(points)} (at least 1) passable or missing={is_open}")


def was_open(sc: Scene, p: Point) -> bool:
    """The map itself leaves this point walkable: no pathing paint on its cell
    or a cell beside it (the engine blends the paint; run 20261120-153031: one
    cell painted 128 read passable at one point and blocked at another), and
    no tree or unit within its reach (their footprints block)."""
    cx, cy = int(p[0]), int(p[1])
    if sc.prior is None or sc.prior[max(0, cy - 1) : cy + 2, max(0, cx - 1) : cx + 2].max() != 0:
        return False
    return all(math.hypot(p[0] - x, p[1] - y) > reach for x, y, reach in sc.things)


def _rim(checks, data: dict, sc: Scene, index: int, rim: Rim) -> int:
    """A rim fall group: its basin is cut in the engine ground, and the step
    blocks no ground the map left walkable. Returns how many points were on
    such ground."""
    section = f"r{index}_basin"
    eng = _f(data, section, "s0Ground")
    new, old = bilinear(sc.vz, *rim.basin), bilinear(sc.before, *rim.basin)
    print(f"{section} raw: at={rim.basin} engine={eng} built={new:.3f} before={old:.3f} pass={data.get(section, {}).get('s0Pass')} rocks={rim.rocks}")
    if eng is None:
        _report(checks, f"{section} sample read", False, "missing")
        return 0
    _report(checks, f"{section} engine ground = built ground", abs(eng - new) <= VERTEX_TOL, f"off={abs(eng - new):.3f} tol={VERTEX_TOL}")
    # Negative: the ground from before the step is absent.
    _report(checks, f"{section} basin is cut, the uncut ground is absent", old - new >= MOVED and abs(eng - new) < abs(eng - old), f"cut={old - new:.3f} (at least {MOVED})")
    # Negative: nothing the step made blocks. Only ground the map left walkable
    # can show that; the rest is listed, not judged. The control is the pool
    # cells of the water features, which read not passable.
    points = [(rim.basin, data.get(section, {}).get("s0Pass"))]
    points += [(p, data.get(f"r{index}_rocks", {}).get(f"s{k}Pass")) for k, p in enumerate(rim.rocks)]
    missing = [f"{p[0]:.1f},{p[1]:.1f}" for p, v in points if v is None]
    judged = [(p, v) for p, v in points if was_open(sc, p)]
    blocked = [f"{p[0]:.1f},{p[1]:.1f}" for p, v in judged if v is not True]
    skipped = [f"{p[0]:.1f},{p[1]:.1f}={v}" for p, v in points if not was_open(sc, p)]
    print(f"r{index} raw: points={len(points)} on ground the map left walkable={len(judged)} not judged (painted or under a tree)={skipped}")
    _report(checks, f"r{index}_walk every sample read", bool(rim.rocks) and not missing, f"rocks={len(rim.rocks)} (at least 1) missing={missing}")
    _report(checks, f"r{index}_walk basin and rocks block no walkable ground", not blocked, f"judged={len(judged)} blocked={blocked}")
    return len(judged)


def _stand(checks, data: dict, sc: Scene, section: str) -> None:
    x, y, h, g = (_f(data, section, key) for key in ("x", "y", "marineH", "ground"))
    if None in (x, y, h, g):
        _report(checks, f"{section} marine read", False, "missing")
        return
    built, old = bilinear(sc.vz, x, y), bilinear(sc.before, x, y)
    print(f"{section} raw: x={x:.2f} y={y:.2f} marineH={h:.3f} ground={g:.3f} built={built:.3f} before={old:.3f} alive={data.get(section, {}).get('alive')}")
    _report(checks, f"{section} marine is on ground the step moved", abs(built - old) >= MOVED, f"moved={built - old:.3f}")
    # UnitGetHeight is above the engine ground: a standing Marine reads 0.
    _report(checks, f"{section} marine stands on the engine ground", abs(h) <= 0.01, f"marineH={h:.3f}")
    _report(checks, f"{section} engine ground under the marine = built ground", abs(g - built) <= SPOT_TOL, f"ground={g:.3f} built={built:.3f}")


def path_points(row: dict) -> list[Point]:
    out = []
    for k in range(int(row.get("pathCount", 0) or 0)):
        text = row.get(f"path{k:03d}")
        if text is None:
            break
        x, y = str(text).split(",")
        out.append((int(x) / 100.0, int(y) / 100.0))
    return out


def water_depth(sc: Scene, site: Site, p: Point) -> float:
    """Water over the ground under a point; 0 or less where there is none."""
    x0, y0, x1, y1 = site.rect
    if not (x0 <= p[0] <= x1 and y0 <= p[1] <= y1):
        return 0.0
    return sc.levels[site.water] - bilinear(sc.vz, p[0], p[1])


def _walk(checks, data: dict, sc: Scene, site: Site, section: str, s: Samples) -> None:
    row = data.get(section, {})
    path = path_points(row)
    print(f"{section} raw: start={s.start} end={s.end} startPass={row.get('startPass')} endPass={row.get('endPass')} moveIssued={row.get('moveIssued')} samples={len(path)} endOrders={row.get('endOrders')} alive={row.get('alive')}")
    # The control: open ground is passable, so a blocked pool cell means something.
    _report(checks, f"{section} start is passable", row.get("startPass") is True, f"startPass={row.get('startPass')}")
    _report(checks, f"{section} move order issued", row.get("moveIssued") is True and row.get("alive") is True, f"issued={row.get('moveIssued')} alive={row.get('alive')}")
    if len(path) < 2:
        _report(checks, f"{section} path read", False, f"samples={len(path)}")
        return
    went = max(math.dist(path[0], p) for p in path)
    nearest = min(math.dist(s.end, p) for p in path)
    deepest = max(water_depth(sc, site, p) for p in path)
    print(f"{section} raw: first={path[0]} last={path[-1]} went={went:.2f} nearest to the pool middle={nearest:.2f} deepest water={deepest:.3f}")
    _report(checks, f"{section} the marine walked", went >= 1.0, f"went={went:.2f}")
    # Negative: the Marine is never in the pool.
    inside = sum(water_depth(sc, site, p) >= config.NO_PATH_DEPTH for p in path)
    _report(checks, f"{section} the marine never stands in the pool", inside == 0, f"samples in water {config.NO_PATH_DEPTH} deep={inside} of {len(path)} deepest={deepest:.3f}")


def _pipe(checks, data: dict, sc: Scene, section: str, placed: tuple[str, float, float]) -> None:
    kind, px, py = placed
    row = data.get(section, {})
    print(f"{section} raw: type={kind} placed=({px},{py}) {row}")
    _report(checks, f"{section} one {kind} in the game", row.get("count") == 1, f"count={row.get('count')}")
    x, y, facing, height, g = (_f(data, section, key) for key in ("x", "y", "facing", "height", "ground"))
    if None in (x, y, facing, height, g):
        _report(checks, f"{section} unit read", False, "missing")
        return
    _report(checks, f"{section} stands where it was placed", math.dist((x, y), (px, py)) <= 0.01, f"x={x:.3f} y={y:.3f}")
    built = bilinear(sc.vz, x, y)
    _report(checks, f"{section} stands on the built ground", abs(height) <= 0.01 and abs(g - built) <= SPOT_TOL, f"height={height:.3f} ground={g:.3f} built={built:.3f}")
    turn = abs((facing - AUTHORED_FACING + 180.0) % 360.0 - 180.0)
    _report(checks, f"{section} faces {AUTHORED_FACING:.0f}: the model is drawn as authored", turn <= 0.5, f"facing={facing:.2f}")


def _turn(a: float, b: float) -> float:
    """Smallest angle between two yaws, degrees."""
    return abs((a - b + 180.0) % 360.0 - 180.0)


def _orbit(checks, ctx, data: dict, sc: Scene, index: int) -> None:
    """The camera circled the site, and the host has its screenshots.

    Camera values are engine state. What the screenshots show is not checked:
    the agent looks at them for scenery only (AGENTS.md)."""
    section = f"s{index}_orbit"
    row = data.get(section, {})
    (x, y), yaw = orbit(sc, index)
    print(f"{section} raw: plan target=({x:.2f},{y:.2f}) yaw={yaw:.1f} turn={ORBIT_TURN} {row}")
    keys = [tag + key for tag in ("start", "mid", "end") for key in ("X", "Y", "Yaw", "Pitch", "Dist")] + ["seconds"]
    if any(row.get(k) is None for k in keys):
        _report(checks, f"{section} camera read", False, f"missing={[k for k in keys if row.get(k) is None]}")
        return
    off = max(math.dist((float(row[t + "X"]), float(row[t + "Y"])), (x, y)) for t in ("start", "mid", "end"))
    _report(checks, f"{section} camera target stays on the site", off <= 1.0, f"off={off:.2f}")
    arm = max(abs(float(row[t + "Dist"]) - ORBIT_DIST) for t in ("start", "mid", "end"))
    tilt = max(abs(float(row[t + "Pitch"]) - ORBIT_PITCH) for t in ("start", "mid", "end"))
    _report(checks, f"{section} camera distance and pitch as planned", arm <= 0.5 and tilt <= 0.5, f"distance off={arm:.2f} pitch off={tilt:.2f}")
    at = [_turn(float(row[t + "Yaw"]), yaw + ORBIT_TURN * share) for t, share in (("start", 0.0), ("mid", 0.5), ("end", 1.0))]
    _report(checks, f"{section} camera yaw follows the orbit", max(at) <= 6.0, f"off start={at[0]:.1f} mid={at[1]:.1f} end={at[2]:.1f}")
    _report(checks, f"{section} orbit lasts {ORBIT_SECONDS:.0f} s of real time", ORBIT_SECONDS <= float(row["seconds"]) <= ORBIT_SECONDS + 2.0, f"seconds={float(row['seconds']):.2f}")
    # Negative: the hero camera is off; nothing pulls the view back to the hero.
    _report(checks, f"{section} camera does not follow the hero", row.get("followsHero") is False and row.get("scene") is True, f"followsHero={row.get('followsHero')} scene={row.get('scene')}")
    # The host hook sets ctx.orbit_shots; without it the check below fails.
    try:
        taken = ctx.orbit_shots
    except AttributeError:
        taken = {}
    shots = taken.get(section, [])
    files = [n for _t, n in shots if (ctx.frames.dir / n).is_file() and (ctx.frames.dir / n).stat().st_size > 0]
    # Each time is the end of a grab, so a slow grab shows as a late shot.
    late = [t - k * SHOT_GAP_S for k, (t, _n) in enumerate(shots)]
    spaced = len(shots) == SHOTS and all(0.0 <= d <= 1.0 for d in late) and shots[-1][0] < ORBIT_SECONDS
    _report(checks, f"{section} {SHOTS} screenshots {SHOT_GAP_S:.0f} s apart, inside the orbit", len(files) == SHOTS and spaced, f"files={files} seconds={[round(t, 2) for t, _n in shots]}")


def check(ctx, data: dict, checks) -> None:
    for error in ctx.errors:
        print(f"{error} FAIL")
        checks.failures += 1
    checks.eq("meta", "", "done", 1)
    checks.eq("meta", "", "realClicks", 0)
    checks.gt("meta", "", "count", 0)
    sc = scene()
    _report(checks, "pipe units placed", len(sc.pipes) >= 1, f"placed={len(sc.pipes)}")
    for k, placed in enumerate(sc.pipes):
        _pipe(checks, data, sc, f"pipe{k}", placed)
    for i, site in enumerate(sc.sites):
        s = samples(sc, i)
        level = sc.levels[site.water]
        _heights(checks, data, sc, f"s{i}_pool", s.pool, level, "pool")
        _heights(checks, data, sc, f"s{i}_dry", s.dry, level, "dry")
        _heights(checks, data, sc, f"s{i}_far", s.far, level, "far")
        _cells(checks, data, f"s{i}_cells", s.cells, "painted pool cells")
        _stand(checks, data, sc, f"s{i}_stand")
        _walk(checks, data, sc, site, f"s{i}_walk", s)
        _orbit(checks, ctx, data, sc, i)
    rims = rim_groups()
    _report(checks, "rim fall groups built", rim_config.MIN_SITES <= len(rims) <= rim_config.MAX_SITES, f"groups={len(rims)} want {rim_config.MIN_SITES}..{rim_config.MAX_SITES}")
    judged = sum(_rim(checks, data, sc, i, rim) for i, rim in enumerate(rims))
    # The walkable check is not empty: enough points lie on ground the map left walkable.
    _report(checks, "rim points on ground the map left walkable", judged >= rim_config.MIN_SITES, f"judged={judged} (at least {rim_config.MIN_SITES})")


