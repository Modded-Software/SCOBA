def points_galaxy(sc: Scene) -> str:
    body = ["// Generated by scripts/testkit/profiles/waterfeat.py.", "void gf_WaterFeatPoints () {"]
    for i, rim in enumerate(rim_groups()):
        body.append(f'    gf_WfSample("r{i}_basin", 0, {rim.basin[0]:.3f}, {rim.basin[1]:.3f});')
        body += [f'    gf_WfSample("r{i}_rocks", {k}, {x:.3f}, {y:.3f});' for k, (x, y) in enumerate(rim.rocks)]
    for k, (kind, _x, _y) in enumerate(sc.pipes):
        body.append(f'    gf_WfPipe("pipe{k}", "{kind}");')
    for i in range(len(sc.sites)):
        s = samples(sc, i)
        for name, points in (("pool", s.pool), ("dry", s.dry), ("far", s.far), ("cells", s.cells)):
            body += [f'    gf_WfSample("s{i}_{name}", {k}, {x:.3f}, {y:.3f});' for k, (x, y) in enumerate(points)]
        body.append("    BankSave(gv_dbgBank);")
        body.append(f'    gf_WfStand("s{i}_stand", {s.stand[0]:.3f}, {s.stand[1]:.3f});')
        body.append(f'    gf_WfWalk("s{i}_walk", {s.start[0]:.3f}, {s.start[1]:.3f}, {s.end[0]:.3f}, {s.end[1]:.3f});')
    body += ["}", "", "void gf_WaterFeatOrbits () {"]
    for i in range(len(sc.sites)):
        (x, y), yaw = orbit(sc, i)
        body.append(f'    gf_WfOrbit("s{i}_orbit", {x:.3f}, {y:.3f}, {yaw:.3f}, {ORBIT_TURN:.1f}, {ORBIT_SECONDS:.1f}, {ORBIT_DIST:.1f}, {ORBIT_PITCH:.1f}, {ORBIT_HEIGHT:.1f});')
    body.append("}")
    return "\n".join(body) + "\n"


