"""Crushable flora table for systems/crush.galaxy.

Goliaths and Queens remove the CRUSH_KINDS doodads they walk into
(libNtve_gf_RemoveDoodadsinRegion) and leave a debris model at each. A
script cannot list placed doodads, so the build writes their positions here,
sorted into BUCKET-sized cells: a walker checks only the 3 x 3 cells around it.

src/ holds an empty copy of the data table so the source map compiles;
apply_flora writes the real one into the built map.
"""

from __future__ import annotations

from pathlib import Path

from . import config

DATA_FILE = Path("scripts") / "app" / "data" / "flora_crush.galaxy"
CRUSH_KINDS = tuple(config.FAMILIES)  # all generated flora (operator, 2026-11-16)
BUCKET = 8.0
GRID = 32  # 256 / BUCKET
CHUNK = 300  # statements per load function (Galaxy function size)
SIZE_REF = 3.0  # family spacing of a "size 1" plant; effect size = scale * spacing / SIZE_REF


def effect_size(kind: str, scale: float) -> float:
    """Crush effect size: the doodad scale times the kind's footprint."""
    return round(scale * config.FAMILIES[kind].spacing / SIZE_REF, 3)


def bucket(x: float, y: float) -> int:
    return min(GRID - 1, max(0, int(y // BUCKET))) * GRID + min(GRID - 1, max(0, int(x // BUCKET)))


def table(plants: list[tuple]) -> list[tuple[int, int, float, float, float, float, int]]:
    """(bucket, kind index, x, y, z, effect size, doodad id) of the crushable
    plants, in bucket order. Input rows are (kind, x, y, z, scale[, id]);
    id 0 means unknown (the crush then removes the doodad instead of fading it)."""
    rows = []
    for row in plants:
        k, x, y, z, s = row[:5]
        ident = row[5] if len(row) > 5 else 0
        if k in CRUSH_KINDS:
            rows.append((bucket(x, y), CRUSH_KINDS.index(k), x, y, z, effect_size(k, s), ident))
    return sorted(rows)


# row y, first x, end x (exclusive), surface height, mean visible depth
# (surface above the visible ground; the splash height above ground, quake.galaxy)
Water = list[tuple[int, int, int, float, float]]
MAP_CELLS = 256


def water_spans(terrain) -> Water:
    """Runs of wet cells per row, for the water effects (systems/quake.galaxy).

    A cell is wet when the water surface is at least WATER_FX_DEPTH above the
    ground the flora sits on (computed ground + GROUND_LIFT). Operator
    2026-11-16: the in-game WorldHeight read 0 everywhere (waterprobe run
    20261116-124538), so the whole water rectangle counted as water and
    dry banks rippled and splashed.
    """
    import numpy as np

    surface = terrain.depth + terrain.height
    wet = np.isfinite(terrain.depth) & (terrain.depth - config.GROUND_LIFT >= config.WATER_FX_DEPTH)
    spans: Water = []
    n = wet.shape[0]
    for y in range(n):
        x = 0
        while x < n:
            if not wet[y, x]:
                x += 1
                continue
            start = x
            while x < n and wet[y, x]:
                x += 1
            seen = terrain.depth[y, start:x] - config.GROUND_LIFT
            spans.append((y, start, x, round(float(surface[y, start:x].max()), 3), round(float(seen.mean()), 3)))
    return spans


def galaxy(plants: list[tuple[str, float, float, float, float]], water: Water | None = None) -> str:
    water = water or []
    rows = table(plants)
    n = len(rows)
    starts = [0] * (GRID * GRID)
    lens = [0] * (GRID * GRID)
    for i, (b, *_rest) in enumerate(rows):
        if lens[b] == 0:
            starts[b] = i
        lens[b] += 1
    stmts = []
    for i, (_b, k, x, y, z, s, ident) in enumerate(rows):
        stmts.append(f"    gv_crushX[{i}] = {x:.3f}; gv_crushY[{i}] = {y:.3f}; gv_crushZ[{i}] = {z:.3f}; gv_crushKind[{i}] = {k}; gv_crushS[{i}] = {s:.3f}; gv_crushId[{i}] = {ident};")
    for b in range(GRID * GRID):
        if lens[b]:
            stmts.append(f"    gv_crushStart[{b}] = {starts[b]}; gv_crushLen[{b}] = {lens[b]};")
    out = [
        "// Generated by scripts/flora/crush.py. Do not edit.",
        f"const int c_CRUSH_COUNT = {n};",
        f"const int c_CRUSH_GRID = {GRID};",
        f"const fixed c_CRUSH_BUCKET = {BUCKET:.1f};",
        f"const int c_CRUSH_KINDS = {len(CRUSH_KINDS)};",
        f"fixed[{max(n, 1)}] gv_crushX;",
        f"fixed[{max(n, 1)}] gv_crushY;",
        f"fixed[{max(n, 1)}] gv_crushZ;",
        f"int[{max(n, 1)}] gv_crushKind;",
        f"fixed[{max(n, 1)}] gv_crushS;",
        f"int[{max(n, 1)}] gv_crushId;",
        f"bool[{max(n, 1)}] gv_crushGone;",
        f"int[{GRID * GRID}] gv_crushStart;",
        f"int[{GRID * GRID}] gv_crushLen;",
        f"string[{len(CRUSH_KINDS)}] gv_crushKindName;",
        f"const int c_WATER_SPANS = {len(water)};",
        f"const int c_WATER_ROWS = {MAP_CELLS};",
        f"int[{MAP_CELLS}] gv_waterRowFirst;",
        f"int[{MAP_CELLS}] gv_waterRowCount;",
        f"int[{max(len(water), 1)}] gv_waterX0;",
        f"int[{max(len(water), 1)}] gv_waterX1;",
        f"fixed[{max(len(water), 1)}] gv_waterZ;",
        f"fixed[{max(len(water), 1)}] gv_waterD;",
        "",
    ]
    rows_seen: dict[int, list[int]] = {}
    for i, (y, x0, x1, z, d) in enumerate(water):
        stmts.append(f"    gv_waterX0[{i}] = {x0}; gv_waterX1[{i}] = {x1}; gv_waterZ[{i}] = {z:.3f}; gv_waterD[{i}] = {d:.3f};")
        rows_seen.setdefault(y, []).append(i)
    for y, idx in sorted(rows_seen.items()):
        stmts.append(f"    gv_waterRowFirst[{y}] = {idx[0]}; gv_waterRowCount[{y}] = {len(idx)};")
    chunks = [stmts[i : i + CHUNK] for i in range(0, len(stmts), CHUNK)]
    for c, body in enumerate(chunks):
        out += [f"void gf_CrushLoad{c} () {{", *body, "}", ""]
    out.append("void gf_CrushLoad () {")
    out += [f'    gv_crushKindName[{i}] = "{k}";' for i, k in enumerate(CRUSH_KINDS)]
    out += [f"    gf_CrushLoad{c}();" for c in range(len(chunks))]
    out += ["}", ""]
    return "\n".join(out)


def main() -> int:
    """Write the empty table into src/ (the build writes the real table)."""
    from project_root import project_root

    path = project_root() / "src" / "SCOBA.SC2Map" / DATA_FILE
    path.write_text(galaxy([]), encoding="utf-8")
    print(f"wrote empty table {path}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
