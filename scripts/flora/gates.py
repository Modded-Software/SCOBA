"""Lane gates: one point on the painted dirt between each spawn and its X region.

Waves walk spawn -> gate -> X region -> other side's gate -> enemy spawn, so
they follow the curved dirt lanes instead of cutting through the jungle.
Each gate is a circle on the dirt: its centre is the lane middle (farthest
from the dirt edge) near the middle of the dirt stretch of that half-lane;
its radius is GATE_SHARE of the half lane width there. Units pick a random
point inside, so they do not all walk the same line.
"""

from __future__ import annotations

from pathlib import Path
from typing import NamedTuple

import numpy as np

from . import config, dirt
from . import lanes as lanes_mod
from .grid import distance_to, shortest_path
from .scene import Scene
from .terrain import Terrain

DATA_FILE = Path("scripts") / "app" / "data" / "lane_gates.galaxy"
OFF_DIRT = 25.0  # route cost factor off the dirt
SNAP = 6  # search this far (cells) for the lane middle
GATE_SHARE = 0.8  # gate radius / half lane width ("almost as broad as the lane")
MIN_DIRT = 10  # a half-lane route must cross at least this many dirt cells
# Galaxy lane index, as in the spawn triggers' gv_xLOCATIONS.
GALAXY_LANE = {"center": 1, "bottom": 2, "top": 3}
SIDES = ("Zerg", "Terran")


class Gate(NamedTuple):
    lane: str
    side: str
    x: float
    y: float
    radius: float


def find(map_dir: Path, terrain: Terrain, scene: Scene) -> list[Gate]:
    n = terrain.height.shape[0]
    on_dirt = dirt.dirt_cells(map_dir, n)
    base = lanes_mod.base_cost(terrain, scene)
    cost = np.where(on_dirt, base, base * OFF_DIRT)
    half_width = distance_to(~on_dirt | ~np.isfinite(base))
    gates = []
    for route in config.LANE_ROUTES:
        cross = scene.regions[route.cross]
        for side, spawn_name in zip(SIDES, (route.zerg, route.terran)):
            spawn = scene.regions[spawn_name]
            start = lanes_mod.nearest_open(cost, spawn.x, spawn.y)
            goal = lanes_mod.nearest_open(cost, cross.x, cross.y)
            path = shortest_path(cost, start, goal)
            on = [(x, y) for x, y in path if on_dirt[y, x]]
            if len(on) < MIN_DIRT:
                raise ValueError(f"lane {route.name} {side}: route crosses only {len(on)} dirt cells")
            mx, my = on[len(on) // 2]
            ys, xs = np.mgrid[max(0, my - SNAP) : min(n, my + SNAP + 1), max(0, mx - SNAP) : min(n, mx + SNAP + 1)]
            near = (xs - mx) ** 2 + (ys - my) ** 2 <= SNAP * SNAP
            score = np.where(near, half_width[ys, xs], -1.0)
            k = np.unravel_index(int(np.argmax(score)), score.shape)
            gx, gy = int(xs[k]), int(ys[k])
            gates.append(Gate(route.name, side, gx + 0.5, gy + 0.5, round(GATE_SHARE * float(half_width[gy, gx]), 2)))
    return gates


def problems(map_dir: Path, gates: list[Gate], n: int) -> list[str]:
    """Every point a unit can pick must be on dirt."""
    on_dirt = dirt.dirt_cells(map_dir, n)
    out = []
    for g in gates:
        r = int(np.ceil(g.radius))
        for dy in range(-r, r + 1):
            for dx in range(-r, r + 1):
                if dx * dx + dy * dy <= g.radius * g.radius and not on_dirt[int(g.y) + dy, int(g.x) + dx]:
                    out.append(f"gate {g.lane} {g.side} at ({g.x},{g.y}) r {g.radius} reaches off the dirt")
                    return out
        if g.radius < 1.0:
            out.append(f"gate {g.lane} {g.side} at ({g.x},{g.y}) is narrower than 1 cell")
    return out


def galaxy(gates: list[Gate]) -> str:
    lines = [
        "// Generated by scripts/flora/gates.py. Do not edit.",
        "// [side][lane]: side 0 Zerg, 1 Terran; lane 1 center, 2 bottom, 3 top.",
        "point[2][4] gv_gateAt;",
        "fixed[2][4] gv_gateRadius;",
        "",
        "void gf_GateLoad () {",
    ]
    for g in gates:
        s, lane = SIDES.index(g.side), GALAXY_LANE[g.lane]
        lines.append(f"    gv_gateAt[{s}][{lane}] = Point({g.x:.2f}, {g.y:.2f}); gv_gateRadius[{s}][{lane}] = {g.radius:.2f};")
    lines += ["}", ""]
    return "\n".join(lines)


def build(map_dir: Path) -> str:
    from . import scene as scene_mod
    from . import terrain as terrain_mod

    terrain = terrain_mod.load(map_dir)
    gates = find(map_dir, terrain, scene_mod.load(map_dir))
    bad = problems(map_dir, gates, terrain.height.shape[0])
    if bad:
        raise ValueError("lane gates failed:\n" + "\n".join(bad))
    return galaxy(gates)


def write(map_dir: Path) -> None:
    (map_dir / DATA_FILE).write_text(build(map_dir), encoding="utf-8")


def check(map_dir: Path) -> list[str]:
    path = map_dir / DATA_FILE
    have = path.read_text(encoding="utf-8").replace("\r\n", "\n") if path.exists() else ""
    return [] if have == build(map_dir) else [f"{DATA_FILE} does not match the lane dirt"]


def main() -> int:
    """Write the empty table into src/ (the build writes the real one)."""
    from project_root import project_root

    path = project_root() / "src" / "SCOBA.SC2Map" / DATA_FILE
    path.write_text(galaxy([]), encoding="utf-8")
    print(f"wrote empty table {path}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
