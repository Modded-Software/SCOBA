ALLOWED_ANIMATION_TOKENS |= frozenset(str(index).zfill(2) for index in range(1, 100))
ALLOWED_ANIMATION_TOKENS |= frozenset(chr(index) for index in range(ord("A"), ord("Z") + 1))


def animation_tokens(text: str) -> list[str]:
    return [token for token in text.replace(",", " ").split() if token]


def invalid_animation_tokens(text: str) -> list[str]:
    return [token for token in animation_tokens(text) if token not in ALLOWED_ANIMATION_TOKENS]


def validate_animation_name(text: str) -> str:
    if not animation_tokens(text):
        raise ValueError("animation name is empty")
    invalid = invalid_animation_tokens(text)
    if invalid:
        raise ValueError(f"unknown animation tokens {invalid} in {text!r}")
    return text


def normalized_animation_name(text: str) -> str:
    validate_animation_name(text)
    return " ".join(animation_tokens(text))